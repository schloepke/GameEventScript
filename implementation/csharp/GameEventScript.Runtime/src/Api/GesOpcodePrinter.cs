            GesBytecodeOpCode.EndsWith => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.Contains => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.ContainsAny => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.ContainsAll => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.ContainsValue => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.Union => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.Intersect => [TargetRegister, LeftRegister, RightRegister],
            GesBytecodeOpCode.Zip => [TargetRegister, LeftRegister, RightRegister],
