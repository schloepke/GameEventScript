"""Generate the shared terminal width table of both CLIs.

Widths come from Python's Unicode data. Width 0: nonspacing/enclosing marks,
format and control characters (except U+00AD) and Hangul medial/final jamo.
Width 2: East Asian Wide/Fullwidth, including the unassigned defaults, and the
regional indicators, the only Emoji_Presentation scalars without a wide East
Asian Width. Everything else is 1.

The cluster data of the C# CLI comes from the Swift toolchain's segmentation:
the scalars that attach to a preceding cluster, the prepended scalars that join
a following one and the controls that end one (grapheme rules GB4, GB5, GB9,
GB9a and GB9b, for scalars newer than .NET's Unicode data), and
the Indic conjunct linkers, consonants and extenders of rule GB9c, which .NET's
text elements lack. Python has no such data, so generation needs Swift; the
Swift CLI tests verify all of it against that segmentation.

--check verifies that the C# table and the two Swift files (CLI widths, test-only
cluster data) hold the same tables and, when this Python's Unicode version
matches the recorded one, that the widths are current.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSHARP = ROOT / "implementation/csharp/GameEventScript.Tool/src/ToolTextWidths.cs"
SWIFT = ROOT / "implementation/swift/GameEventScriptTool/Sources/GameEventScriptTool/ToolTextWidths.swift"
# Swift segments natively, so its cluster data exists only for the tests that verify it.
SWIFT_CLUSTERS = ROOT / "implementation/swift/GameEventScriptTool/Tests/GameEventScriptToolTests/ToolTextClusters.swift"
HEADER = "// Copyright 2026 Stephan Schlöpke\n// SPDX-License-Identifier: Apache-2.0\n"
NOTICE = "// Generated by scripts/generate-terminal-widths.py from Unicode {version}; do not edit.\n"
WIDTH_TABLES = ("starts", "widths")
CLUSTER_TABLES = ("clusterAttachers", "clusterPrepends", "clusterControls", "conjunctLinkers", "conjunctConsonants", "conjunctExtenders")

# An attacher extends a consonant; a prepend joins a following letter; a
# control does not take a following combining acute. A linker joins two Devanagari consonants into one Character; a consonant
# joins a preceding consonant and virama without extending a lone consonant; an
# extender (InCB=Extend) extends a consonant and keeps the conjunct joined
# before the virama. The Swift tests repeat this probe and check both positions.
CONJUNCT_PROBE = r"""
let ka = "\u{915}"
let virama = "\u{94D}"
var linkers: [String] = []
var consonants: [String] = []
var extenders: [String] = []
var attachers: [String] = []
var controls: [String] = []
var prepends: [String] = []
for value in UInt32(0)...0x10FFFF {
    guard let scalar = Unicode.Scalar(value) else { continue }
    let text = String(scalar)
    if (text + "\u{301}").count == 2 { controls.append(String(value, radix: 16)) }
    if (text + "a").count == 1 { prepends.append(String(value, radix: 16)) }
    if (ka + text).count == 1 {
        attachers.append(String(value, radix: 16))
        if (ka + text + ka).count == 1 { linkers.append(String(value, radix: 16)) }
        else if (ka + text + virama + "\u{937}").count == 1 { extenders.append(String(value, radix: 16)) }
    } else if scalar.properties.generalCategory == .otherLetter && (ka + virama + text).count == 1 {
        consonants.append(String(value, radix: 16))
    }
}
print(linkers.joined(separator: " "))
print(consonants.joined(separator: " "))
print(extenders.joined(separator: " "))
print(attachers.joined(separator: " "))
print(controls.joined(separator: " "))
print(prepends.joined(separator: " "))
"""


def width(scalar: int) -> int:
    if 0x1160 <= scalar <= 0x11FF or 0xD7B0 <= scalar <= 0xD7FF:
        return 0
    if 0x1F1E6 <= scalar <= 0x1F1FF:
        return 2
    character = chr(scalar)
    category = unicodedata.category(character)
    if category in ("Mn", "Me", "Cc") or category == "Cf" and scalar != 0xAD:
        return 0
    return 2 if unicodedata.east_asian_width(character) in ("W", "F") else 1


def runs() -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for scalar in range(0x110000):
        if 0xD800 <= scalar <= 0xDFFF:
            continue
        value = width(scalar)
        if not result or result[-1][1] != value:
            result.append((scalar, value))
    return result


def clusters() -> dict[str, list[int]]:
    try:
        output = subprocess.run(["swift", "-"], input=CONJUNCT_PROBE, capture_output=True, text=True, check=True).stdout.splitlines()
    except FileNotFoundError:
        raise RuntimeError("generating the cluster data needs the Swift toolchain on PATH") from None
    except subprocess.CalledProcessError as error:
        raise RuntimeError(f"the Swift cluster probe failed:\n{error.stderr.strip()}") from None
    if len(output) < 6:
        raise RuntimeError("the Swift cluster probe printed no data")
    linkers, consonants, extenders, attachers, controls, prepends = ([int(value, 16) for value in line.split()] for line in output[-6:])
    if not all((linkers, consonants, extenders, attachers, controls, prepends)):
        raise RuntimeError("the Swift toolchain reported no cluster scalars")
    return {
        "clusterAttachers": ranges(attachers),
        "clusterPrepends": ranges(prepends),
        "clusterControls": ranges(controls),
        "conjunctLinkers": linkers,
        "conjunctConsonants": consonants,
        "conjunctExtenders": ranges(extenders),
    }


def ranges(values: list[int]) -> list[int]:
    """Collapse sorted scalars into inclusive start/end pairs."""
    result: list[int] = []
    for value in values:
        if result and result[-1] == value - 1:
            result[-1] = value
        else:
            result += [value, value]
    return result


def rows(values: list[str], indent: str) -> str:
    return "\n".join(indent + " ".join(values[index:index + 16]) for index in range(0, len(values), 16))


def hexadecimal(values: list[int]) -> str:
    return rows([f"0x{value:X}," for value in values], "        ")


def csharp(version: str, table: list[tuple[int, int]], data: dict[str, list[int]]) -> str:
    widths = rows([f"{value}," for _, value in table], "        ")
    return f"""{HEADER}{NOTICE.format(version=version)}
namespace GameEventScript.Tool;

internal static class ToolTextWidths
{{
    // Each run starts at its scalar and lasts until the next start.
    internal static ReadOnlySpan<int> Starts =>
    [
{hexadecimal([start for start, _ in table])}
    ];

    internal static ReadOnlySpan<byte> Widths =>
    [
{widths}
    ];

    // Inclusive start/end pairs of the scalars that attach to a preceding cluster (GB9/GB9a), that join a following
    // one (GB9b), and of the controls that end one (GB4/GB5), from Swift's segmentation, for scalars newer than .NET's
    // Unicode data.
    internal static ReadOnlySpan<int> ClusterAttachers =>
    [
{hexadecimal(data["clusterAttachers"])}
    ];

    internal static ReadOnlySpan<int> ClusterPrepends =>
    [
{hexadecimal(data["clusterPrepends"])}
    ];

    internal static ReadOnlySpan<int> ClusterControls =>
    [
{hexadecimal(data["clusterControls"])}
    ];

    // Sorted Indic_Conjunct_Break Linker and Consonant scalars of grapheme rule GB9c.
    internal static ReadOnlySpan<int> ConjunctLinkers =>
    [
{hexadecimal(data["conjunctLinkers"])}
    ];

    internal static ReadOnlySpan<int> ConjunctConsonants =>
    [
{hexadecimal(data["conjunctConsonants"])}
    ];

    // Inclusive start/end pairs of the InCB=Extend scalars that keep a conjunct joined.
    internal static ReadOnlySpan<int> ConjunctExtenders =>
    [
{hexadecimal(data["conjunctExtenders"])}
    ];
}}
"""


def swift(version: str, table: list[tuple[int, int]]) -> str:
    widths = rows([f"{value}," for _, value in table], "        ")
    return f"""{HEADER}{NOTICE.format(version=version)}
enum ToolTextWidths {{
    // Each run starts at its scalar and lasts until the next start.
    static let starts: [UInt32] = [
{hexadecimal([start for start, _ in table])}
    ]

    static let widths: [UInt8] = [
{widths}
    ]
}}
"""


def swift_clusters(version: str, data: dict[str, list[int]]) -> str:
    arrays = "\n\n".join(f"    static let {name}: [UInt32] = [\n{hexadecimal(values)}\n    ]" for name, values in data.items())
    return f"""{HEADER}{NOTICE.format(version=version)}
// The C# CLI's cluster data, which the tests verify against Swift's native segmentation. Attachers, prepends,
// controls and conjunct extenders are inclusive start/end pairs.
enum ToolTextClusters {{
{arrays}
}}
"""


def parse(text: str, names: tuple[str, ...]) -> tuple[str, dict[str, list[int]]]:
    """Read the version and the named tables independently of line breaks and indentation."""
    version = re.search(r'\bfrom Unicode ([0-9.]+);', text)
    if version is None:
        raise ValueError("the generated width table has no Unicode version")
    tables: dict[str, list[int]] = {}
    for name in names:
        match = re.search(rf"\b{name}\s*(?::\s*\[\w+\]\s*)?=>?\s*\[([^\]]*)\]", text, re.I)
        if match is None:
            raise ValueError(f"the generated width table has no {name} array")
        tables[name] = [int(value, 0) for value in re.findall(r"0x[0-9A-Fa-f]+|\d+", match.group(1))]
    return version.group(1), tables


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the generated files instead of writing them")
    arguments = parser.parse_args()
    version = unicodedata.unidata_version
    if not arguments.check:
        table = runs()
        try:
            data = clusters()
        except RuntimeError as error:
            print(f"error: {error}", file=sys.stderr)
            return 1
        CSHARP.write_text(csharp(version, table, data), encoding="utf-8")
        SWIFT.write_text(swift(version, table), encoding="utf-8")
        SWIFT_CLUSTERS.write_text(swift_clusters(version, data), encoding="utf-8")
        print(f"Generated {len(table)} width runs and the cluster data from Unicode {version}.")
        return 0
    try:
        recorded, tables = parse(CSHARP.read_text(encoding="utf-8"), WIDTH_TABLES + CLUSTER_TABLES)
        swift_version, swift_tables = parse(SWIFT.read_text(encoding="utf-8"), WIDTH_TABLES)
        cluster_version, cluster_tables = parse(SWIFT_CLUSTERS.read_text(encoding="utf-8"), CLUSTER_TABLES)
        if (swift_version, cluster_version, swift_tables | cluster_tables) != (recorded, recorded, tables):
            print("error: the C# and Swift terminal width tables differ.", file=sys.stderr)
            return 1
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if recorded != version:
        print(f"Both width tables match (Unicode {recorded}); Python provides Unicode {version}, so currency is not checked.")
        return 0
    table = runs()
    if tables["starts"] != [start for start, _ in table] or tables["widths"] != [value for _, value in table]:
        print("error: the terminal width tables are stale; run scripts/generate-terminal-widths.py.", file=sys.stderr)
        return 1
    print(f"Both width tables are current for Unicode {version}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
