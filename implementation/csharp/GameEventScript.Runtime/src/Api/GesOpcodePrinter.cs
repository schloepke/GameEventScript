            GesBytecodeOpCode.MapBuilderFinish => [TargetRegister, BuilderRegister],
            GesBytecodeOpCode.DistinctBuilderCreate => [TargetRegister],
            GesBytecodeOpCode.DistinctBuilderAdd => [BuilderRegister, KeyRegister, ValueRegister],
            GesBytecodeOpCode.DistinctBuilderFinish => [TargetRegister, BuilderRegister],
            GesBytecodeOpCode.GroupBuilderCreate => [TargetRegister],
            GesBytecodeOpCode.GroupBuilderAdd => [BuilderRegister, KeyRegister, ValueRegister],
            GesBytecodeOpCode.GroupBuilderFinish => [TargetRegister, BuilderRegister],
            GesBytecodeOpCode.OrderBuilderCreate => [TargetRegister],
            GesBytecodeOpCode.OrderBuilderAdd => [BuilderRegister, KeyRegister, ValueRegister],
            GesBytecodeOpCode.OrderBuilderFinishAscending => [TargetRegister, BuilderRegister],
