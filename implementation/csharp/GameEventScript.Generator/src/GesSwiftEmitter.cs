namespace GameEventScript.Generator;

// Writes Swift 6 without Foundation: a Sendable struct per fixed-width schema and a final class per schema with Text or
// List storage, with properties in wire order, write and read over the bit primitives, and constants inlined as literals or
// bit patterns.
internal static partial class GesSwiftEmitter
{
    internal static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "Any", "Protocol", "Self", "Type", "as", "associatedtype", "break", "case", "catch", "class", "continue", "default",
        "defer", "deinit", "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate", "for", "func", "guard",
        "if", "import", "in", "init", "inout", "internal", "is", "let", "nil", "open", "operator", "private", "precedencegroup",
        "protocol", "public", "repeat", "rethrows", "return", "self", "static", "struct", "subscript", "super", "switch",
        "throw", "throws", "true", "try", "typealias", "var", "where", "while"
    };

    // Members that converting to and from GES values adds; reading them overloads read.
    private static readonly string[] ValueReserved = ["toValue", "toMessage"];

    private static readonly string[] Reserved =
    [
        "schemaHash", "bindingHash", "maxByteCount", "write", "read", "readKey", "encoded", "encodedByteCount", "writeDelta", "deltaEncoded", "deltaEncodedByteCount", "readDelta", "wireEquals", "copy", "quantize"
    ];

    internal static GesCodeDocument Emit(GesSchemaLayout layout, List<GesPlanType> types, GesSchemaGenerateOptions options, GesModelLayout? packed, GesModelLayout? modelLayout, int extended, HashSet<string>? declared)
    {
        var access = options.Access == GesSchemaAccess.Public ? "public " : "";
        var prologue = new GesSchemaPlanner.Code();

        // Generated code keeps its own layout, as C# analyzers skip <auto-generated> code.
        prologue.Line("// swift-format-ignore-file");
        prologue.Blank();
        prologue.Line("import GameEventScriptRuntime");
        if (GesComputedEmitter.UsesMath(types.ConvertAll(type => type.Layout.Computed))) GesComputedLibrary.MathImport(prologue);
        prologue.Blank();
        var header = GesSchemaPlanner.Header(layout);
        var holder = "__GesSchemas" + GesSchemaPlanner.Suffix(header, options);
        var context = new Context(GesSchemaPlanner.KeyedElements(types), options.Values, holder, options.CheckedExclusivity)
        {
            Computed = GesSchemaPlanner.Computed(types, GesComputedEmitter.Helper(options.Namespace, GesSchemaPlanner.Suffix(header, options)), swift: true)
        };
        var document = new GesCodeDocument
        {
            Header = header,
            Prologue = prologue.ToString(),
            Space = GesSchemaPlanner.Namespace(options.Namespace, Keywords),
            Swift = true,
            Access = access,
            Holds = "schema",
            Parameters = layout.Parameters.Count > 0
        };
        var modelSpace = options.Models is null ? null : GesSchemaPlanner.Namespace(options.Models, Keywords);
        document.Extended = GesSchemaPlanner.Extended(document.Space, extended, modelSpace);
        context.Layout = layout;
        // Packed records are the model types over one word, the shared ones of the model namespace or declared here.
        var models = modelSpace is null ? "" : string.Concat(modelSpace.ConvertAll(part => part + "."));
        foreach (var type in types)
            foreach (var field in type.Fields) GesSchemaPlanner.QualifyPacked(field.Value, models);
        var space = string.Concat(document.Space.ConvertAll(part => part + "."));
        var conversions = new List<(GesPlanType Type, GesModelType Model)>();
        if (modelLayout is not null)
        {
            var conversion = context.Models = new ModelConversion(modelLayout, models, space);
            foreach (var type in types)
                if (type.Kind == GesSchemaKind.Schema && type.Layout.PackedWidth == 0 && conversion.Type(type.Name) is { } model)
                {
                    conversions.Add((type, model));
                    document.Units.Add(new GesCodeUnit(type.Name, code => ModelConversionUnit(code, type, model, access, conversion), outside: true));
                }
        }
        foreach (var type in types)
        {
            if (type.Layout.PackedWidth > 0)
            {
                if (packed is not null) document.Units.Add(new GesCodeUnit(type.Name, code => GesSwiftModelEmitter.PackedType(code, packed, type.Name, access)));

                // A wire root's members extend the type at file scope where the wire code declares it, and are an enum
                // `<Name>Wire` in the wire namespace where the models declare it.
                var sharesModel = packed is null;
                var qualified = (sharesModel ? models : space) + type.Name;
                if (layout.Roots.Contains(type.Name)) document.Units.Add(new GesCodeUnit(type.Name, code => PackedRoot(code, type, access, qualified, context, sharesModel), outside: !sharesModel));
                continue;
            }

            document.Units.Add(new GesCodeUnit(type.Name, code =>
            {
                if (type.Kind == GesSchemaKind.Messages) MessageSet(code, type, access, context);
                else Record(code, type, access, context);
            }));
        }
        var sets = GesSchemaPlanner.TagSets(types, "");
        foreach (var (name, tags) in sets) document.Units.Add(new GesCodeUnit(name, code => TagSetDeclaration(code, name, tags, access)));
        context.TopLevel = GesSchemaPlanner.TopLevel(types, sets);
        if (modelSpace is not null)
        {
            GesSchemaPlanner.ReserveSharedRoots(layout, types, context.TopLevel);
            var modelsRoot = modelSpace.Count > 0 ? modelSpace[0] : null;
            var wireRoot = document.Space.Count > 0 ? document.Space[0] : null;
            // Records and the `<Name>Wire` members name shared packed types inside the wire namespace, where the wire types are
            // in scope; a conversion extends its record at file scope, where only the record's nested types are, and names both
            // namespaces; the model's init(wire:) names the wire namespace beside the model's nested types.
            if (modelsRoot is not null && types.Exists(type => type.Layout.PackedWidth > 0))
            {
                GesSchemaPlanner.CheckModelsRoot(modelsRoot, declared!);
                context.Inside.Add(modelsRoot);
            }

            if (modelsRoot is not null) context.Converted.Add(modelsRoot);
            if (wireRoot is not null)
            {
                context.Converted.Add(wireRoot);
                foreach (var (type, model) in conversions)
                {
                    var names = new List<(string, string)>();
                    foreach (var field in GesModelPlanner.Fields(model)) GesSwiftModelEmitter.Nested(field.Value, names, field.Field.Name);
                    foreach (var (name, origin) in names)
                        if (name == wireRoot)
                            throw new GesGeneratorException(GesGeneratorException.NameCollision, $"In the model '{model.Name}', {origin} is generated as '{name}', which hides the wire namespace through which its conversion names '{type.Name}'.");
                }
            }
        }

        GesSchemaPlanner.CheckTopLevel(context.TopLevel, swift: true);

        // Split files reach the sources of another file, so the holder is internal there.
        var shared = options.Split != GesSchemaSplit.None;
        if (options.Values) document.Units.Add(new GesCodeUnit("", code => ValuesHolder(code, layout, holder, shared), outside: true));
        if (layout.Types.Exists(type => type.Computed.Length > 0))
            document.Units.Add(new GesCodeUnit("", code => GesComputedLibrary.Write(code, context.Computed.HelperName, swift: true, context.Computed.NeedsValues(types.ConvertAll(type => (type.Name, type.Layout.Computed))), GesComputedEmitter.UsesMath(types.ConvertAll(type => type.Layout.Computed)))));
        return document;
    }

    // The keyed-list elements, and whether records convert to and from GES values through the helper type of the file.
    private sealed class Context(HashSet<string> elements, bool values, string holder, bool checkedExclusivity)
    {
        internal GesSchemaLayout Layout { get; set; } = null!;

        // The models that records convert to and from directly, null without `--models`.
        internal ModelConversion? Models { get; set; }

        internal HashSet<string> Elements { get; } = elements;

        internal bool Values { get; } = values;

        internal string Holder { get; } = holder;

        internal GesComputedEmitter Computed { get; set; } = null!;

        // The records and tag sets declared beside each other, which a record's nested type must not hide.
        internal HashSet<string> TopLevel { get; set; } = null!;

        // The first components of the namespaces that a record names inside the wire namespace (Inside) and that a converted
        // record's conversion names (Converted), which the record's nested types must not hide.
        internal List<string> Inside { get; } = [];

        internal List<string> Converted { get; } = [];

        // The attribute of a class's stored properties: without exclusivity checks unless they are asked for.
        internal string Stored(bool isClass) => isClass && !checkedExclusivity ? "@exclusivity(unchecked) " : "";
    }

    private static string Name(string name) => Keywords.Contains(name) ? "`" + name + "`" : name;

    private static string Member(string pascal) => Name(GesSchemaPlanner.Camel(pascal));

    // The byte storage of a Text or Bytes value in `owner`, "self" or another record.
    internal static string Storage(GesPlanValue value, string owner)
        => value.Encoding.Kind == GesLayoutKind.Bytes ? $"{owner}.{Member(value.Base)}" : $"{owner}.{GesSchemaPlanner.Camel(value.Base)}UTF8";

    private static string Kind(GesPlanType type) => type.Kind == GesSchemaKind.Message ? "message" : "schema";

    private static void Record(GesSchemaPlanner.Code code, GesPlanType type, string access, Context context)
    {
        var names = new List<(string, string)>();
        if (!type.IsItem)
            foreach (var reserved in Reserved) names.Add((reserved, "the generated member " + reserved));
        if (!type.IsItem && context.Values)
            foreach (var reserved in ValueReserved) names.Add((reserved, "the generated member " + reserved));
        foreach (var field in type.Fields)
        {
            names.Add((GesSchemaPlanner.Camel(field.Base), "the field " + field.Layout.Name));
            if (field.Optional) names.Add(("has" + field.Base, "the presence of " + field.Layout.Name));
            if (field.Optional && Plain(field.Value)) names.Add((GesSchemaPlanner.Camel(field.Base) + "Optional", "the optional value of " + field.Layout.Name));
            Nested(field.Value, names, field.Layout.Name);
            if (GesCSharpEmitter.IsPooledList(field)) names.Add(("set" + field.Base + "Count", "the element count of " + field.Layout.Name));
            if (GesCSharpEmitter.IsTextList(field)) names.Add((GesSchemaPlanner.Camel(field.Base) + "Values", "the texts of " + field.Layout.Name));
        }

        foreach (var (tag, name, _) in type.Tags) names.Add((GesSchemaPlanner.Camel(name), "the tag #" + tag));
        if (!type.IsItem)
            foreach (var constant in type.Layout.Constants) names.Add((constant.Name, "the let " + constant.Name));
        if (!type.IsItem) GesComputedEmitter.Names(type.Layout.Computed, type.Name, swift: true, names);
        var model = type.IsItem || type.Kind != GesSchemaKind.Schema ? null : context.Models?.Type(type.Name);
        if (model is not null) names.Add(("toModel", "the generated member toModel"));
        GesSchemaPlanner.Unique(type.Name, names, context.TopLevel, model is not null ? context.Converted : context.Inside);

        code.Line(type.IsItem ? "/// An element of the list." : $"/// The {Kind(type)} `:{type.Name}`, read and written without allocation{(type.IsClass ? " once its storage has grown" : "")}.");
        code.Open(type.IsClass ? $"{access}final class {type.Name} {{" : $"{access}struct {type.Name}: Sendable {{");
        if (!type.IsItem)
        {
            Constants(code, type.Layout, access);
            code.Line("static let __paths: [String] = [");
            foreach (var path in type.Paths) code.Line("    " + Quote(path) + ",");
            code.Line("]");
        }

        var stored = context.Stored(type.IsClass);
        var first = type.IsItem;
        foreach (var field in type.Fields)
        {
            Members(code, field, access, stored, first);
            first = false;
        }

        foreach (var (tag, name, _) in type.Tags)
        {
            code.Line($"/// Whether the tag `#{tag}` is set.");
            code.Line($"{stored}{access}var {Member(name)} = false");
        }

        foreach (var field in type.Fields) Pools(code, field.Value, stored);
        foreach (var field in type.Fields) ListAccess(code, field, access);
        if (!type.IsItem) context.Computed.Members(code, type.Name, type.Layout.Computed, access.TrimEnd());
        code.Blank();
        code.Line(type.IsItem ? "/// Creates an element with every field at its zero value." : "/// Creates a record with every field at its zero value.");
        code.Line($"{access}init() {{}}");
        Methods(code, type, access);
        if (type.IsClass && (type.Kind == GesSchemaKind.Schema || type.IsItem)) Sharing(code, type, stored);
        var deltas = type.Kind == GesSchemaKind.Schema && !type.IsItem;
        if (deltas) SameHelpers(code, type);
        Extras(code, type, access, deltas, context.Elements.Contains(type.Name));
        if (context.Values && !type.IsItem) ValueMembers(code, type, access, context.Holder);
        foreach (var field in type.Fields) Declarations(code, field.Value, access, context);
        code.Close();
    }

    private static void Constants(GesSchemaPlanner.Code code, GesLayoutType layout, string access)
    {
        code.Line("/// The schema hash, independent of parameter values.");
        code.Line($"{access}static let schemaHash: UInt64 = 0x{GesSchemaLayoutJson.Hex(layout.Hash)}");
        code.Line("/// The hash over the schema hash and the parameter values this code was generated with.");
        code.Line($"{access}static let bindingHash: UInt64 = 0x{GesSchemaLayoutJson.Hex(layout.BindingHash)}");
        code.Line("/// The size of the largest encoding in bytes.");
        code.Line($"{access}static let maxByteCount = {layout.MaxByteCount.ToString(CultureInfo.InvariantCulture)}");
        Lets(code, layout.Constants, access, "Int64");
    }

    // The lets of a schema, in base units; a Percentage holds its ratio.
    internal static void Lets(GesSchemaPlanner.Code code, List<GesLayoutConstant> constants, string access, string integer)
    {
        foreach (var constant in constants)
        {
            code.Line($"/// `{GesSchemaPlanner.ConstantSource(constant)}`");
            code.Line($"{access}static let {Member(constant.Name)}: {(constant.Integer ? integer : "Double")} = {GesSchemaPlanner.ConstantValue(constant)}");
        }
    }

    private static bool Plain(GesPlanValue value) => !value.IsClass && value.Encoding.Kind is not (GesLayoutKind.Union or GesLayoutKind.Text or GesLayoutKind.Bytes or GesLayoutKind.List);

    private static void Nested(GesPlanValue value, List<(string, string)> names, string field)
    {
        var name = NestedName(value);
        if (name.Length > 0 && value.TagType.Length == 0) names.Add((name, GesSchemaPlanner.NestedTypeOrigin + "of " + field));
        switch (value.Encoding.Kind)
        {
            case GesLayoutKind.Text:
                names.Add((GesSchemaPlanner.Camel(value.Base) + "UTF8", "the UTF-8 bytes of " + field));
                break;
            case GesLayoutKind.List:
                if (value.Encoding.Poly) names.Add((GesSchemaPlanner.Camel(value.Base) + "Poly", "the polygon view of " + field));
                if (value.Item is not null) names.Add((value.Item.Name, GesSchemaPlanner.NestedTypeOrigin + "of the elements of " + field));
                else Nested(value.Element!, names, field);
                break;
            case GesLayoutKind.Union:
                foreach (var alternative in value.Alternatives)
                {
                    if (alternative.Encoding.Kind != GesLayoutKind.Nothing) names.Add((GesSchemaPlanner.Camel(alternative.Base), $"the alternative {alternative.Label} of {field}"));
                    Nested(alternative, names, field);
                }

                break;
        }
    }

    private static string NestedName(GesPlanValue value) => value.Encoding.Kind switch
    {
        GesLayoutKind.Tag => value.TagType.Length > 0 ? value.TagType : value.Base + "Tag",
        GesLayoutKind.Flags => value.Base + "Flags",
        GesLayoutKind.Union => value.Base + "Alternative",
        _ => ""
    };

    private static string TypeName(GesPlanValue value) => value.Encoding.Kind switch
    {
        GesLayoutKind.Boolean => "Bool",
        GesLayoutKind.Integer => "Int64",
        GesLayoutKind.Quantized or GesLayoutKind.Float => "Double",
        GesLayoutKind.Schema => value.Packed?.Type ?? value.Encoding.Schema,
        GesLayoutKind.Text => "String",
        GesLayoutKind.Bytes => "[UInt8]",
        GesLayoutKind.Point => "GesPoint",
        GesLayoutKind.Vector => "GesVector",
        GesLayoutKind.Box => "GesBox",
        GesLayoutKind.Disc => "GesDisc",
        GesLayoutKind.List => $"[{ElementName(value)}]",
        _ => NestedName(value)
    };

    private static string ElementName(GesPlanValue list) => list.Item is not null ? list.Item.Name : TypeName(list.Element!);

    private static string Zero(GesPlanValue value) => value.Encoding.Kind switch
    {
        GesLayoutKind.Boolean => "false",
        GesLayoutKind.Integer => "0",
        GesLayoutKind.Quantized or GesLayoutKind.Float => "0.0",
        GesLayoutKind.Tag => "." + Name(value.Encoding.Tags[0]),
        GesLayoutKind.Union => "." + Member(value.Alternatives[0].Label),
        GesLayoutKind.List or GesLayoutKind.Bytes or GesLayoutKind.Flags => "[]",
        GesLayoutKind.Box => "GesBox(GesPoint(), GesPoint())",
        GesLayoutKind.Disc => "GesDisc(radius: 0)",
        GesLayoutKind.Schema when value.Packed is not null => TypeName(value) + "(uncheckedRawValue: 0)",
        _ => TypeName(value) + "()"
    };

    // `var` for a local that later code assigns, `let` for one it only reads, so that Swift warns about neither.
    private static string Binding(bool assigned) => assigned ? "var" : "let";

    private static void Members(GesSchemaPlanner.Code code, GesPlanField field, string access, string stored, bool first)
    {
        if (!first) code.Blank();
        if (field.Optional)
        {
            code.Line($"/// Whether `{field.Layout.Name}` is present.");
            code.Line($"{stored}{access}var has{field.Base} = false");
        }

        Member(code, field.Value, $"The field `{field.Layout.Name}`", access, stored);
        if (field.Optional && Plain(field.Value))
        {
            var name = Member(field.Base);
            code.Line($"/// The field `{field.Layout.Name}` as an optional value, nil when absent.");
            code.Open($"{access}var {GesSchemaPlanner.Camel(field.Base)}Optional: {TypeName(field.Value)}? {{");
            code.Line($"get {{ self.has{field.Base} ? self.{name} : nil }}");
            code.Open("set {");
            code.Line($"self.has{field.Base} = newValue != nil");
            code.Line($"if let newValue {{ self.{name} = newValue }}");
            code.Close();
            code.Close();
        }

        if (field.Value.Encoding.Kind != GesLayoutKind.Union) return;
        foreach (var alternative in field.Value.Alternatives)
        {
            if (alternative.Encoding.Kind == GesLayoutKind.Nothing) continue;
            Member(code, alternative, $"The value of `{field.Layout.Name}` when its alternative is `{alternative.Label}`", access, stored);
        }
    }

    private static void Member(GesSchemaPlanner.Code code, GesPlanValue value, string summary, string access, string stored)
    {
        if (value.Encoding.Kind != GesLayoutKind.Text)
        {
            code.Line($"/// {summary}{Description(value)}.");
            code.Line($"{stored}{access}var {Member(value.Base)}: {TypeName(value)} = {Zero(value)}");
            if (!value.Encoding.Poly) return;
            code.Line($"/// {summary} as a polygon; reading it allocates.");
            code.Line($"{access}var {Member(value.Base + "Poly")}: GesPoly {{ GesPoly({Member(value.Base)}) }}");
            return;
        }

        var bytes = GesSchemaPlanner.Camel(value.Base) + "UTF8";
        code.Line($"/// {summary} as UTF-8 bytes{(value.Encoding.TagName ? ", a tag name without #" : "")}, which are checked when the record is written.");
        code.Line($"{stored}{access}var {bytes}: [UInt8] = []");
        code.Line($"/// {summary} as a string; reading and setting it allocate.");
        code.Open($"{access}var {Member(value.Base)}: String {{");
        code.Line($"get {{ String(decoding: self.{bytes}, as: UTF8.self) }}");
        code.Line($"set {{ self.{bytes} = Array(newValue.utf8) }}");
        code.Close();
    }

    // Sets a pooled list to a count of reused elements, as a read does, and for texts offers them as strings.
    private static void ListAccess(GesSchemaPlanner.Code code, GesPlanField field, string access)
    {
        if (!GesCSharpEmitter.IsPooledList(field)) return;
        var value = field.Value;
        var list = "self." + Member(value.Base);
        var pool = $"self.__{GesSchemaPlanner.Camel(value.Base)}Pool";
        code.Blank();
        code.Line($"/// Sets `{field.Layout.Name}` to `count` elements that the record reuses, as a read does; their fields keep earlier values until they are set.");
        code.Open($"{access}func set{value.Base}Count(_ count: Int) {{");
        code.Line("precondition(count >= 0, \"A count is not negative.\")");
        code.Line($"{list}.removeAll(keepingCapacity: true)");
        code.Open("for position in 0..<count {");
        code.Line($"if position == {pool}.count {{ {pool}.append({ElementName(value)}()) }}");
        code.Line($"{list}.append({pool}[position])");
        code.Close();
        code.Close();
        if (!GesCSharpEmitter.IsTextList(field)) return;
        var text = Member(value.Item!.Fields[0].Base);
        code.Blank();
        code.Line($"/// The elements of `{field.Layout.Name}` as strings; reading and setting allocate, and setting reuses the elements.");
        code.Open($"{access}var {GesSchemaPlanner.Camel(value.Base)}Values: [String] {{");
        code.Line($"get {{ {list}.map {{ $0.{text} }} }}");
        code.Open("set {");
        code.Line($"set{value.Base}Count(newValue.count)");
        code.Line($"for (index, text) in newValue.enumerated() {{ {list}[index].{text} = text }}");
        code.Close();
        code.Close();
    }

    // The instances a list of classes reuses when it is read again.
    private static void Pools(GesSchemaPlanner.Code code, GesPlanValue value, string stored)
    {
        if (value.Encoding.Kind == GesLayoutKind.Union)
            foreach (var alternative in value.Alternatives) Pools(code, alternative, stored);
        if (value.Encoding.Kind == GesLayoutKind.List && value.Element!.IsClass) code.Line($"{stored}private var __{GesSchemaPlanner.Camel(value.Base)}Pool: [{ElementName(value)}] = []");
    }

    private static string Description(GesPlanValue value)
    {
        var encoding = value.Encoding;
        return encoding.Kind switch
        {
            GesLayoutKind.Quantized or GesLayoutKind.Float or GesLayoutKind.Integer when encoding.Unit != "none" => $", in {encoding.Unit}",
            GesLayoutKind.Point or GesLayoutKind.Vector or GesLayoutKind.Box or GesLayoutKind.Disc when encoding.Unit != "none" => $", in {encoding.Unit}",
            GesLayoutKind.List when encoding.Poly => $", the points of a polygon{(encoding.Unit != "none" ? " in " + encoding.Unit : "")}, at most {encoding.MaxCount.ToString(CultureInfo.InvariantCulture)}",
            GesLayoutKind.Union => ", the selected alternative",
            GesLayoutKind.List => $", at most {encoding.MaxCount.ToString(CultureInfo.InvariantCulture)} elements",
            _ => ""
        };
    }

    private static void Methods(GesSchemaPlanner.Code code, GesPlanType type, string access)
    {
        var mutating = type.IsClass ? "" : "mutating ";
        if (!type.IsItem)
        {
            code.Blank();
            PublicMethods(code, access, mutating, ["try __writeFields(&writer, Self.__paths, 0)"], ["try __readFields(&reader, Self.__paths, 0)"], "record");
            var key = type.Fields.Count > 0 && type.Fields[0].Key ? type.Fields[0] : null;
            if (key is not null)
            {
                code.Blank();
                code.Line("/// Reads the key, which comes first, before a caller chooses a baseline.");
                code.Line("/// - Throws: `GesWireError` when the data ends before the key does or holds an invalid key.");
                code.Open($"{access}static func readKey(from data: UnsafeRawBufferPointer) throws(GesWireError) -> {TypeName(key.Value)} {{");
                code.Line("var reader = GesBitReader(data: data)");
                code.Line("let paths = Self.__paths");
                code.Line("let at = 0");
                code.Line($"var key: {TypeName(key.Value)} = {Zero(key.Value)}");
                Read(code, key.Value, "key");
                code.Line("return key");
                code.Close();
            }
        }

        code.Blank();
        code.Open($"func __writeFields(_ writer: inout GesBitWriter, _ paths: [String], _ at: Int{LevelParameter(type)}) throws(GesWireError) {{");
        foreach (var field in type.Fields)
        {
            var target = "self." + Member(field.Base);
            if (field.Optional)
            {
                code.Open($"if self.has{field.Base} {{");
                code.Line("try writer.write(1, width: 1)");
                Write(code, field.Value, target);
                code.Close("} else {");
                code.Line("    try writer.write(0, width: 1)");
                code.Line("}");
            }
            else Write(code, field.Value, target);
        }

        foreach (var (_, name, _) in type.Tags) code.Line($"try writer.write(self.{Member(name)} ? 1 : 0, width: 1)");
        code.Close();
        code.Blank();
        code.Open($"{mutating}func __readFields(_ reader: inout GesBitReader, _ paths: [String], _ at: Int{LevelParameter(type)}) throws(GesWireError) {{");
        foreach (var field in type.Fields)
        {
            var target = "self." + Member(field.Base);
            if (field.Optional)
            {
                code.Line($"self.has{field.Base} = try reader.read(1, path: {Path(field.Value)}) != 0");
                code.Open($"if self.has{field.Base} {{");
                Read(code, field.Value, target);
                if (Plain(field.Value))
                {
                    code.Close("} else {");
                    code.Line($"    {target} = {Zero(field.Value)}");
                    code.Line("}");
                }
                else code.Close();
            }
            else Read(code, field.Value, target);
        }

        foreach (var (_, name, node) in type.Tags) code.Line($"self.{Member(name)} = try reader.read(1, path: paths[at + {node.ToString(CultureInfo.InvariantCulture)}]) != 0");
        code.Close();
    }

    private static void PublicMethods(GesSchemaPlanner.Code code, string access, string mutating, List<string> write, List<string> read, string what)
    {
        code.Line($"/// Writes this {what} into a buffer; `maxByteCount` bytes always suffice.");
        code.Line("/// - Returns: The number of bytes written.");
        code.Line("/// - Throws: `GesWireError` when a value does not fit its field or the buffer is too small.");
        code.Open($"{access}func write(into buffer: UnsafeMutableRawBufferPointer) throws(GesWireError) -> Int {{");
        code.Line("var writer = GesBitWriter(into: buffer)");
        foreach (var line in write) code.Line(line);
        code.Line("return try writer.finish()");
        code.Close();
        code.Blank();
        code.Line($"/// Counts the bytes that `write(into:)` writes for this {what}, without writing them.");
        code.Line("/// - Throws: `GesWireError` when a value does not fit its field.");
        code.Open($"{access}func encodedByteCount() throws(GesWireError) -> Int {{");
        code.Line("var writer = GesBitWriter.counting()");
        foreach (var line in write) code.Line(line);
        code.Line("return try writer.finish()");
        code.Close();
        code.Blank();
        code.Line($"/// Writes this {what} into a new array of its exact size, which `encodedByteCount()` counts first.");
        code.Line("/// - Throws: `GesWireError` when a value does not fit its field.");
        code.Open($"{access}func encoded() throws(GesWireError) -> [UInt8] {{");
        code.Line("let buffer = UnsafeMutableRawBufferPointer.allocate(byteCount: Swift.max(try encodedByteCount(), 1), alignment: 8)");
        code.Line("defer { buffer.deallocate() }");
        code.Line("let count = try write(into: buffer)");
        code.Line("return Array(buffer[0..<count])");
        code.Close();
        code.Blank();
        code.Line($"/// Reads a {what} from untrusted data into this instance. After an error its values are unspecified.");
        code.Line("/// - Parameters:");
        code.Line("///   - data: The data; it may continue after the record.");
        code.Line("///   - byteLimit: An optional limit on the bytes of this record.");
        code.Line("/// - Returns: The number of bytes the record occupies.");
        code.Line($"/// - Throws: `GesWireError` when the data is no valid {what}.");
        code.Line("@discardableResult");
        code.Open($"{access}{mutating}func read(from data: UnsafeRawBufferPointer, byteLimit: Int = .max) throws(GesWireError) -> Int {{");
        code.Line("var reader = GesBitReader(data: data, byteLimit: byteLimit)");
        foreach (var line in read) code.Line(line);
        code.Line("return try reader.finish()");
        code.Close();
        code.Blank();
        code.Line($"/// Reads a {what} from bytes into this instance. After an error its values are unspecified.");
        code.Line("/// - Returns: The number of bytes the record occupies.");
        code.Line($"/// - Throws: `GesWireError` when the bytes are no valid {what}.");
        code.Line("@discardableResult");
        code.Open($"{access}{mutating}func read(from bytes: [UInt8], byteLimit: Int = .max) throws(GesWireError) -> Int {{");
        code.Line("let buffer = UnsafeMutableRawBufferPointer.allocate(byteCount: Swift.max(bytes.count, 1), alignment: 8)");
        code.Line("defer { buffer.deallocate() }");
        code.Line("buffer.copyBytes(from: bytes)");
        code.Line("return try read(from: UnsafeRawBufferPointer(rebasing: buffer[0..<bytes.count]), byteLimit: byteLimit)");
        code.Close();
    }

    private static void MessageSet(GesSchemaPlanner.Code code, GesPlanType type, string access, Context context)
    {
        var names = new List<(string, string)> { ("selected", "the selected member"), ("Member", GesSchemaPlanner.NestedTypeOrigin + "of the members") };
        foreach (var reserved in Reserved) names.Add((reserved, "the generated member " + reserved));
        if (context.Values)
            foreach (var reserved in ValueReserved) names.Add((reserved, "the generated member " + reserved));
        foreach (var member in type.Members) names.Add((GesSchemaPlanner.Camel(member), "the member " + member));
        GesSchemaPlanner.Unique(type.Name, names, context.TopLevel);
        var width = type.Layout.MemberWidth.ToString(CultureInfo.InvariantCulture);
        var last = ((ulong)type.Members.Count - 1).ToString(CultureInfo.InvariantCulture);
        code.Line($"/// The message set `:{type.Name}`: one of its messages, read and written without allocation{(type.MembersAreClasses ? " once its storage has grown" : "")}.");
        code.Open(type.MembersAreClasses ? $"{access}final class {type.Name} {{" : $"{access}struct {type.Name}: Sendable {{");
        Constants(code, type.Layout, access);
        code.Line("/// The message this record holds.");
        var stored = context.Stored(type.MembersAreClasses);
        code.Line($"{stored}{access}var selected: Member = .{Member(type.Members[0])}");
        foreach (var member in type.Members)
        {
            code.Line($"/// The message when `selected` is `{GesSchemaPlanner.Camel(member)}`.");
            code.Line($"{stored}{access}var {Member(member)} = {member}()");
        }

        code.Blank();
        code.Line("/// Creates a record that holds the first message, with every field at its zero value.");
        code.Line($"{access}init() {{}}");
        var write = new List<string> { $"try writer.write(UInt64(self.selected.rawValue), width: {width})", "switch self.selected {" };
        var read = new List<string> { $"let index = try reader.read({width}, path: \"\")" };
        if ((ulong)type.Members.Count - 1 < Full(type.Layout.MemberWidth)) read.Add($"if index > {last} {{ throw GesWireError(code: GesWireError.invalidIndex, path: \"\") }}");
        read.AddRange([$"self.selected = Member(rawValue: {Underlying(type.Members.Count)}(index))!", "switch self.selected {"]);
        foreach (var member in type.Members)
        {
            write.AddRange([$"case .{Member(member)}:", $"    try self.{Member(member)}.__writeFields(&writer, {member}.__paths, 0)"]);
            read.AddRange([$"case .{Member(member)}:", $"    try self.{Member(member)}.__readFields(&reader, {member}.__paths, 0)"]);
        }

        write.Add("}");
        read.Add("}");
        code.Blank();
        PublicMethods(code, access, type.MembersAreClasses ? "" : "mutating ", write, read, "message");
        if (context.Values) ValueMembers(code, type, access, context.Holder);
        code.Blank();
        code.Line("/// The messages of the set, in declared order.");
        code.Open($"{access}enum Member: {Underlying(type.Members.Count)}, Sendable {{");
        foreach (var member in type.Members)
        {
            code.Line($"/// The message `{member}`.");
            code.Line($"case {Member(member)}");
        }

        code.Close();
        code.Close();
    }

    private static string Path(GesPlanValue value) => $"paths[at + {value.Node.ToString(CultureInfo.InvariantCulture)}]";

    // A recursive schema's methods take the level of the record, 1 where a caller enters the recursion.
    private static string LevelParameter(GesPlanType type) => type.Depth > 0 ? ", _ level: Int = 1" : "";

    // The level argument of a call into a record: one deeper for the element of a recursive List.
    private static string NextLevel(GesPlanValue value) => value.Recursive ? ", level + 1" : "";

    // The level that the item of a recursive union takes: that of the record holding the List.
    private static string ItemLevel(GesPlanValue element) => element.PassesLevel ? ", level" : "";

    // Opens the levels of a recursive List that hold elements; at its depth the List holds nothing, so data there is deeper.
    private static void OpenLevels(GesSchemaPlanner.Code code, GesPlanValue value, string count)
    {
        var depth = value.Depth.ToString(CultureInfo.InvariantCulture);
        code.Open($"if level >= {depth} {{");
        code.Line($"if {count} > 0 {{ throw GesWireError(code: GesWireError.tooDeep, path: {Path(value)}, detail: \"deeper than depth {depth}\") }}");
        code.Close("} else {");
        code.Indent();
    }

    private static string Throw(string code, GesPlanValue value) => $"throw GesWireError(code: GesWireError.{code}, path: {Path(value)})";

    private static void Write(GesSchemaPlanner.Code code, GesPlanValue value, string target)
    {
        var encoding = value.Encoding;
        var width = encoding.Width.ToString(CultureInfo.InvariantCulture);
        var max = encoding.MaxCount.ToString(CultureInfo.InvariantCulture);
        switch (encoding.Kind)
        {
            case GesLayoutKind.Boolean:
                code.Line($"try writer.write({target} ? 1 : 0, width: 1)");
                break;
            case GesLayoutKind.Integer when !encoding.Range:
                code.Line($"try writer.write(UInt64(bitPattern: {target}), width: 64)");
                break;
            case GesLayoutKind.Integer when encoding.Wrapping:
                code.Line($"try writer.write(GesWireRules.wrappedIndex({target}, lower: {Long(encoding.Lower)}, period: {Unsigned(encoding.MaxIndex + 1)}), width: {width})");
                break;
            case GesLayoutKind.Integer:
                var lower = Unsigned(unchecked((ulong)encoding.Lower));
                code.Line($"if {target} < {Long(encoding.Lower)} || UInt64(bitPattern: {target}) &- {lower} > {Unsigned(encoding.MaxIndex)} {{ {Throw("outOfRange", value)} }}");
                code.Line($"try writer.write(UInt64(bitPattern: {target}) &- {lower}, width: {width})");
                break;
            case GesLayoutKind.Quantized when encoding.Wrapping:
                code.Line("try writer.write(");
                code.Line($"    try GesWireRules.wrappedQuantizedIndex({target}, tenPower: {Double(encoding.TenPower)}, numerator: {Double(encoding.Numerator)}, lower: {Long(encoding.Lower)}, period: {Unsigned(encoding.MaxIndex + 1)}, path: {Path(value)}),");
                code.Line($"    width: {width}");
                code.Line(")");
                break;
            case GesLayoutKind.Quantized:
                code.Line("try writer.write(");
                code.Line($"    try GesWireRules.quantizedIndex({target}, lowerValue: {Bits(encoding.LowerValue)}, upperValue: {Bits(encoding.UpperValue)}, tenPower: {Double(encoding.TenPower)}, numerator: {Double(encoding.Numerator)}, lower: {Long(encoding.Lower)}, path: {Path(value)}),");
                code.Line($"    width: {width}");
                code.Line(")");
                break;
            case GesLayoutKind.Float:
                code.Line($"if {target}.isNaN {{ {Throw("notRepresentable", value)} }}");
                if (encoding.Range) code.Line($"if {target} < {Bits(encoding.LowerValue)} || {target} > {Bits(encoding.UpperValue)} {{ {Throw("outOfRange", value)} }}");
                code.Line($"try writer.write(({target} == 0 ? 0.0 : {target}).bitPattern, width: 64)");
                break;
            case GesLayoutKind.Tag:
                code.Line($"try writer.write(UInt64({target}.rawValue), width: {width})");
                break;
            case GesLayoutKind.Flags:
                if (encoding.Width < 64) code.Line($"if {target}.rawValue > {Unsigned(Full(encoding.Width))} {{ {Throw("unknownTag", value)} }}");
                code.Line($"try writer.write({target}.rawValue, width: {width})");
                break;
            case GesLayoutKind.Text or GesLayoutKind.Bytes:
                var bytes = Storage(value, "self");
                code.Line($"if {bytes}.count > {max} {{ {Throw("tooLong", value)} }}");
                if (encoding.Kind == GesLayoutKind.Text)
                    code.Line(encoding.TagName
                        ? $"if !{bytes}.withUnsafeBytes({{ GesWireRules.isTagName($0) }}) {{ {Throw("invalidTag", value)} }}"
                        : $"if !{bytes}.withUnsafeBytes({{ GesWireRules.isValidUTF8($0) }}) {{ {Throw("invalidText", value)} }}");
                code.Line($"try writer.write(UInt64({bytes}.count), width: {width})");
                code.Line($"try writer.writeBytes({bytes})");
                break;
            case GesLayoutKind.List:
                if (value.Depth > 0) OpenLevels(code, value, target + ".count");
                code.Line($"if {target}.count > {max} {{ {Throw("tooLong", value)} }}");
                code.Line($"try writer.write(UInt64({target}.count), width: {width})");
                code.Open($"for item in {target} {{");
                if (value.Item is not null) code.Line($"try item.__writeFields(&writer, paths, at + {value.Element!.Node.ToString(CultureInfo.InvariantCulture)}{ItemLevel(value.Element)})");
                else Write(code, value.Element!, "item");
                code.Close();
                if (value.Depth > 0) code.Close();
                break;
            case GesLayoutKind.Point or GesLayoutKind.Vector:
                foreach (var axis in value.Axes) Write(code, axis, target + "." + Member(axis.Base));
                foreach (var axis in GesSchemaPlanner.Omitted(value)) code.Line($"if {target}.{Member(axis)} != 0 {{ {Throw("typeMismatch", value)} }}");
                break;
            case GesLayoutKind.Box:
                foreach (var corner in value.Corners) Write(code, corner, target + "." + Member(corner.Base));
                break;
            case GesLayoutKind.Disc:
                foreach (var part in value.Corners) Write(code, part, target + "." + Member(part.Base));
                if (value.Corners.Count == 1) code.Line($"if {target}.radius != 0 {{ {Throw("typeMismatch", value)} }}");
                break;
            case GesLayoutKind.Schema when value.Packed is not null:
                PackedWrite(code, value, target);
                break;
            case GesLayoutKind.Schema:
                code.Line($"try {target}.__writeFields(&writer, paths, at + {(value.Node + 1).ToString(CultureInfo.InvariantCulture)}{NextLevel(value)})");
                break;
            case GesLayoutKind.Union:
                code.Line($"switch {target} {{");
                for (var index = 0; index < value.Alternatives.Count; index++)
                {
                    var alternative = value.Alternatives[index];
                    code.Open($"case .{Member(alternative.Label)}:");
                    code.Line($"try writer.write({index.ToString(CultureInfo.InvariantCulture)}, width: {width})");
                    if (alternative.Encoding.Kind != GesLayoutKind.Nothing) Write(code, alternative, "self." + Member(alternative.Base));
                    code.Close("");
                }

                code.Line("}");
                break;
        }
    }

    private static void Read(GesSchemaPlanner.Code code, GesPlanValue value, string target)
    {
        var encoding = value.Encoding;
        var width = encoding.Width.ToString(CultureInfo.InvariantCulture);
        var max = encoding.MaxCount.ToString(CultureInfo.InvariantCulture);
        switch (encoding.Kind)
        {
            case GesLayoutKind.Boolean:
                code.Line($"{target} = try reader.read(1, path: {Path(value)}) != 0");
                break;
            case GesLayoutKind.Integer when !encoding.Range:
                code.Line($"{target} = Int64(bitPattern: try reader.read(64, path: {Path(value)}))");
                break;
            case GesLayoutKind.Flags:
                code.Line($"{target} = {NestedName(value)}(rawValue: try reader.read({width}, path: {Path(value)}))");
                break;
            case GesLayoutKind.Integer or GesLayoutKind.Quantized or GesLayoutKind.Tag:
                code.Open("do {");
                code.Line($"let index = try reader.read({width}, path: {Path(value)})");
                var largest = encoding.Kind == GesLayoutKind.Tag ? (ulong)encoding.Tags.Count - 1 : encoding.MaxIndex;
                if (largest < Full(encoding.Width)) code.Line($"if index > {Unsigned(largest)} {{ {Throw("invalidIndex", value)} }}");
                code.Line(encoding.Kind switch
                {
                    GesLayoutKind.Integer => $"{target} = Int64(bitPattern: {Unsigned(unchecked((ulong)encoding.Lower))} &+ index)",
                    GesLayoutKind.Quantized => $"{target} = GesWireRules.quantizedValue(index, lower: {Long(encoding.Lower)}, numerator: {Long(encoding.Numerator)}, tenPower: {Double(encoding.TenPower)})",
                    _ => $"{target} = {NestedName(value)}(rawValue: {Underlying(encoding.Tags.Count)}(index))!"
                });
                code.Close();
                break;
            case GesLayoutKind.Float:
                code.Open("do {");
                code.Line($"let bits = try reader.read(64, path: {Path(value)})");
                code.Line("let value = Double(bitPattern: bits)");
                code.Line($"if value.isNaN || bits == 0x8000_0000_0000_0000{(encoding.Range ? " || value.isInfinite" : "")} {{ {Throw("invalidNumber", value)} }}");
                if (encoding.Range) code.Line($"if value < {Bits(encoding.LowerValue)} || value > {Bits(encoding.UpperValue)} {{ {Throw("outOfRange", value)} }}");
                code.Line($"{target} = value");
                code.Close();
                break;
            case GesLayoutKind.Text or GesLayoutKind.Bytes:
                var bytes = Storage(value, "self");
                code.Open("do {");
                code.Line($"let count = Int(try reader.read({width}, path: {Path(value)}))");
                code.Line($"if count > {max} {{ {Throw("invalidCount", value)} }}");
                code.Line($"try reader.readBytes(count, into: &{bytes}, path: {Path(value)})");
                if (encoding.Kind == GesLayoutKind.Text)
                    code.Line(encoding.TagName
                        ? $"if !{bytes}.withUnsafeBytes({{ GesWireRules.isTagName($0) }}) {{ {Throw("invalidTag", value)} }}"
                        : $"if !{bytes}.withUnsafeBytes({{ GesWireRules.isValidUTF8($0) }}) {{ {Throw("invalidText", value)} }}");
                code.Close();
                break;
            case GesLayoutKind.List:
                var element = value.Element!;
                var name = ElementName(value);
                if (value.Depth > 0)
                {
                    // The deepest level reads no count, since its List takes no bits.
                    code.Open($"if level >= {value.Depth.ToString(CultureInfo.InvariantCulture)} {{");
                    code.Line($"{target}.removeAll(keepingCapacity: true)");
                    code.Close("} else {");
                    code.Indent();
                }
                else code.Open("do {");
                code.Line($"let count = Int(try reader.read({width}, path: {Path(value)}))");
                code.Line($"if count > {max} {{ {Throw("invalidCount", value)} }}");
                code.Line($"{target}.removeAll(keepingCapacity: true)");
                if (element.Packed is not null)
                {
                    PackedList(code, value, target, "count");
                    code.Close();
                    break;
                }

                code.Open(element.IsClass ? "for position in 0..<count {" : "for _ in 0..<count {");
                if (element.IsClass)
                {
                    var pool = $"self.__{GesSchemaPlanner.Camel(value.Base)}Pool";
                    code.Line($"if position == {pool}.count {{ {pool}.append({name}()) }}");
                    code.Line($"let item = {pool}[position]");
                }
                else if (value.Item is not null || element.Encoding.Kind is GesLayoutKind.Point or GesLayoutKind.Vector or GesLayoutKind.Schema) code.Line(value.Item is not null ? $"var item = {name}()" : $"var item = {Zero(element)}");
                else code.Line($"var item: {name} = {Zero(element)}");
                if (value.Item is not null) code.Line($"try item.__readFields(&reader, paths, at + {element.Node.ToString(CultureInfo.InvariantCulture)}{ItemLevel(element)})");
                else Read(code, element, "item");
                code.Line($"{target}.append(item)");
                code.Close();
                code.Close();
                break;
            case GesLayoutKind.Point or GesLayoutKind.Vector:
                foreach (var axis in value.Axes) Read(code, axis, target + "." + Member(axis.Base));
                foreach (var axis in GesSchemaPlanner.Omitted(value)) code.Line($"{target}.{Member(axis)} = 0");
                break;
            case GesLayoutKind.Box:
                // The corners arrive as two Points; the box orders them.
                code.Open("do {");
                foreach (var corner in value.Corners)
                {
                    code.Line($"var {corner.Label}{N(value.Node)} = GesPoint()");
                    Read(code, corner, corner.Label + N(value.Node));
                }

                code.Line($"{target} = GesBox(lower{N(value.Node)}, upper{N(value.Node)})");
                code.Close();
                break;
            case GesLayoutKind.Disc:
                // The centre and the radius, which a block can leave out; the disc takes the radius's magnitude.
                code.Open("do {");
                code.Line($"var center{N(value.Node)} = GesPoint()");
                code.Line($"{Binding(value.Corners.Count > 1)} radius{N(value.Node)} = 0.0");
                foreach (var part in value.Corners) Read(code, part, part.Label + N(value.Node));
                code.Line($"{target} = GesDisc(center: center{N(value.Node)}, radius: radius{N(value.Node)})");
                code.Close();
                break;
            case GesLayoutKind.Schema when value.Packed is not null:
                PackedRead(code, value, target);
                break;
            case GesLayoutKind.Schema:
                code.Line($"try {target}.__readFields(&reader, paths, at + {(value.Node + 1).ToString(CultureInfo.InvariantCulture)}{NextLevel(value)})");
                break;
            case GesLayoutKind.Union:
                code.Open("do {");
                code.Line($"let choice = try reader.read({width}, path: {Path(value)})");
                if ((ulong)value.Alternatives.Count - 1 < Full(encoding.Width)) code.Line($"if choice > {Unsigned((ulong)value.Alternatives.Count - 1)} {{ {Throw("invalidIndex", value)} }}");
                code.Line($"{target} = {NestedName(value)}(rawValue: {Underlying(value.Alternatives.Count)}(choice))!");
                code.Line("switch choice {");
                for (var index = 0; index < value.Alternatives.Count; index++)
                {
                    var alternative = value.Alternatives[index];
                    if (alternative.Encoding.Kind == GesLayoutKind.Nothing) continue;
                    code.Open($"case {index.ToString(CultureInfo.InvariantCulture)}:");
                    Read(code, alternative, "self." + Member(alternative.Base));
                    code.Close("");
                }

                code.Open("default:");
                code.Line("break");
                code.Close("}");
                code.Close();
                break;
        }
    }

    private static void Declarations(GesSchemaPlanner.Code code, GesPlanValue value, string access, Context context)
    {
        var name = NestedName(value);
        switch (value.Encoding.Kind)
        {
            case GesLayoutKind.Tag:
                if (value.TagType.Length > 0) break;
                code.Blank();
                code.Line("/// The tags of the field, in declared order.");
                code.Open($"{access}enum {name}: {Underlying(value.Encoding.Tags.Count)}, Sendable {{");
                foreach (var tag in value.Encoding.Tags)
                {
                    code.Line($"/// The tag `#{tag}`.");
                    code.Line($"case {Name(tag)}");
                }

                code.Close();
                break;
            case GesLayoutKind.Flags:
                FlagsDeclaration(code, name, value.Encoding.Tags, access);
                break;
            case GesLayoutKind.Union:
                code.Blank();
                code.Line("/// The alternatives of the field, in declared order.");
                code.Open($"{access}enum {name}: {Underlying(value.Alternatives.Count)}, Sendable {{");
                foreach (var alternative in value.Alternatives)
                {
                    code.Line($"/// The alternative `:{alternative.Label}`.");
                    code.Line($"case {Member(alternative.Label)}");
                }

                code.Close();
                foreach (var alternative in value.Alternatives) Declarations(code, alternative, access, context);
                break;
            case GesLayoutKind.List:
                if (value.Item is not null)
                {
                    code.Blank();
                    Record(code, value.Item, access, context);
                }
                else Declarations(code, value.Element!, access, context);
                break;
        }
    }

    private static string Underlying(int count) => count <= 256 ? "UInt8" : count <= 65536 ? "UInt16" : "UInt32";

    // A named tag set, declared once beside the records that use it.
    internal static void TagSetDeclaration(GesSchemaPlanner.Code code, string name, List<string> tags, string access)
    {
        code.Blank();
        code.Line($"/// The tag set `:{name}`, in declared order.");
        code.Open($"{access}enum {name}: {Underlying(tags.Count)}, Sendable {{");
        foreach (var tag in tags)
        {
            code.Line($"/// The tag `#{tag}`.");
            code.Line($"case {Name(tag)}");
        }

        code.Close();
    }

    // One bit per member in declared order, so the raw value is the wire mask. A member may not take the name of the mask.
    internal static void FlagsDeclaration(GesSchemaPlanner.Code code, string name, List<string> members, string access)
    {
        var names = new List<(string, string)> { ("rawValue", "the generated member rawValue") };
        foreach (var member in members) names.Add((member, "the member #" + member));
        GesSchemaPlanner.Unique(name, names);
        code.Blank();
        code.Line("/// The members of the field, one bit each in declared order.");
        code.Open($"{access}struct {name}: OptionSet, Hashable, Sendable, Codable {{");
        code.Line("/// The mask, one bit per member in declared order.");
        code.Line($"{access}let rawValue: UInt64");
        code.Blank();
        code.Line("/// Creates the members of a mask.");
        code.Line($"{access}init(rawValue: UInt64) {{ self.rawValue = rawValue }}");
        for (var index = 0; index < members.Count; index++)
        {
            code.Blank();
            code.Line($"/// The member `#{members[index]}`.");
            code.Line($"{access}static let {Name(members[index])} = {name}(rawValue: 1 << {index.ToString(CultureInfo.InvariantCulture)})");
        }

        code.Close();
    }

    private static ulong Full(int width) => width >= 64 ? ulong.MaxValue : (1UL << width) - 1;

    private static string Long(long value) => value == long.MinValue ? "Int64.min" : value.ToString(CultureInfo.InvariantCulture);

    private static string Unsigned(ulong value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Double(long value) => value.ToString(CultureInfo.InvariantCulture) + ".0";

    private static string Bits(double value) => $"Double(bitPattern: 0x{GesSchemaLayoutJson.Hex((ulong)BitConverter.DoubleToInt64Bits(value))})";

    private static string Quote(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
