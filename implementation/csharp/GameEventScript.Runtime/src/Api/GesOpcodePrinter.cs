            GesBytecodeOpCode.ParseLiteral => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.CheckType => [TargetRegister, SourceRegister, TypeKind],
            GesBytecodeOpCode.CheckCustomType => [TargetRegister, SourceRegister, CustomTypeName],
            GesBytecodeOpCode.CheckUnit => [TargetRegister, SourceRegister, Unit],
