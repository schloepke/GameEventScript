            GesBytecodeOpCode.JumpIfTrue => [ConditionRegister, JumpTarget],
            GesBytecodeOpCode.JumpIfFalse => [ConditionRegister, JumpTarget],
            GesBytecodeOpCode.JumpIfNotTrue => [ConditionRegister, JumpTarget],
