extension GesMath {
    @inline(__always)
    static func executeXor<Output: GesValueOutput>(_ i: GameEventScriptBytecodeInstruction, _ s: GesVmState, _ c: GameEventScriptContext, _ a: GesValue, _ b: GesValue, sink: Output) throws -> Output.Result {
        guard let av = a.truth, let bv = b.truth else { return sink.nothing }
        return sink.boolean(av != bv)
    }
}
