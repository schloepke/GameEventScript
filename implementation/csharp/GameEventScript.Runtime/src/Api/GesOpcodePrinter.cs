            GesBytecodeOpCode.IteratorClose => [IteratorRegister],

            GesBytecodeOpCode.HasAny => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.HasAll => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.Distinct => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.SortAscending => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.SortDescending => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.Reverse => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.Shuffle => [TargetRegister, SourceRegister],
            GesBytecodeOpCode.ListBuilderCreate => [TargetRegister],
