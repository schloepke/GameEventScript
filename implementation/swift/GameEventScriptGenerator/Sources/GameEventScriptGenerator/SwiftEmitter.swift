// Writes Swift 6 without Foundation: a Sendable struct per fixed-width schema and a final class per schema with Text or
// List storage, with properties in wire order, write and read over the bit primitives, and constants inlined as literals or
// bit patterns.
enum GesSwiftEmitter {
    static let keywords: Set<String> = [
        "Any", "Protocol", "Self", "Type", "as", "associatedtype", "break", "case", "catch", "class", "continue", "default",
        "defer", "deinit", "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate", "for", "func", "guard",
        "if", "import", "in", "init", "inout", "internal", "is", "let", "nil", "open", "operator", "private", "precedencegroup",
        "protocol", "public", "repeat", "rethrows", "return", "self", "static", "struct", "subscript", "super", "switch",
        "throw", "throws", "true", "try", "typealias", "var", "where", "while",
    ]

    // Members that converting to and from GES values adds; reading them overloads read.
    static let valueReserved = ["toValue", "toMessage"]

    static let reserved = [
        "schemaHash", "bindingHash", "maxByteCount", "write", "read", "readKey", "encoded", "encodedByteCount", "writeDelta", "deltaEncoded", "deltaEncodedByteCount", "readDelta", "wireEquals", "copy", "quantize",
    ]

    typealias Code = GesSchemaPlanner.Code
    typealias Names = [(name: String, origin: String)]

    static func emit(
        _ layout: GesSchemaLayout,
        _ types: [GesPlanType],
        _ options: GesSchemaGenerateOptions,
        _ packed: GesModelLayout?,
        _ modelLayout: GesModelLayout?,
        extended: Int,
        declared: Set<String>?
    ) throws(GesGeneratorError) -> GesCodeDocument {
        let access = options.access == .public ? "public " : ""
        var prologue = Code()
        // Generated code keeps its own layout, as C# analyzers skip <auto-generated> code.
        prologue.line("// swift-format-ignore-file")
        prologue.blank()
        prologue.line("import GameEventScriptRuntime")
        if !layout.networks.isEmpty { prologue.line("import GameEventScriptNetwork") }
        let schemaSet = try GesSchemaSetReference.from(options)
        for module in options.imports { prologue.line("import " + module) }
        if GesComputedEmitter.usesMath(types.map(\.layout.computed)) { GesComputedLibrary.mathImport(&prologue) }
        prologue.blank()
        let header = GesSchemaPlanner.header(layout)
        let holder = schemaSet?.qualified ?? "__GesSchemas" + GesSchemaPlanner.suffix(header, options)
        let computed = GesSchemaPlanner.computed(types, GesComputedEmitter.helper(options.namespace, GesSchemaPlanner.suffix(header, options)), swift: true)
        let sets = GesSchemaPlanner.tagSets(types, "")
        // Packed records are the model types over one word, the shared ones of the model namespace or declared here.
        var modelParts: [String]?
        if let modelSpace = options.models { modelParts = try GesSchemaPlanner.namespace(modelSpace, keywords) }
        let models = modelParts.map { $0.map { $0 + "." }.joined() } ?? ""
        for type in types {
            for field in type.fields { GesSchemaPlanner.qualifyPacked(field.value, models) }
        }
        let spaceParts = try GesSchemaPlanner.namespace(options.namespace, keywords)
        let space = spaceParts.map { $0 + "." }.joined()
        var topLevel = GesSchemaPlanner.topLevel(types, sets, layout.networks)
        let conversion = modelLayout.map { ModelConversion($0, models, space) }
        var conversions: [(type: GesPlanType, model: GesModelType)] = []
        if let conversion {
            for type in types where type.kind == .schema && type.layout.packedWidth == 0 {
                if let model = conversion.type(type.name) { conversions.append((type, model)) }
            }
        }
        var inside: [String] = []
        var converted: [String] = []
        if let modelParts {
            try GesSchemaPlanner.reserveSharedRoots(layout, types, &topLevel)
            let modelsRoot = modelParts.first
            let wireRoot = spaceParts.first
            // Records and the `<Name>Wire` members name shared packed types inside the wire namespace, where the wire types are
            // in scope; a conversion extends its record at file scope, where only the record's nested types are, and names both
            // namespaces; the model's init(wire:) names the wire namespace beside the model's nested types.
            if let modelsRoot, types.contains(where: { $0.layout.packedWidth > 0 }) {
                try GesSchemaPlanner.checkModelsRoot(modelsRoot, declared ?? [])
                inside.append(modelsRoot)
            }
            if let modelsRoot { converted.append(modelsRoot) }
            if let wireRoot {
                converted.append(wireRoot)
                for (type, model) in conversions {
                    var names: Names = []
                    for field in GesModelPlanner.fields(model) { GesSwiftModelEmitter.nested(field.value, &names, field.field.name) }
                    for (name, origin) in names where name == wireRoot {
                        throw GesGeneratorError(
                            GesGeneratorError.nameCollision,
                            "In the model '\(model.name)', \(origin) is generated as '\(name)', which hides the wire namespace through which its conversion names '\(type.name)'."
                        )
                    }
                }
            }
        }
        try schemaSet?.reserve(&topLevel)
        let context = Context(
            layout: layout,
            models: conversion,
            elements: GesSchemaPlanner.keyedElements(types),
            values: options.values,
            holder: holder,
            schemaSet: schemaSet != nil,
            checkedExclusivity: options.checkedExclusivity,
            computed: computed,
            topLevel: topLevel,
            inside: inside,
            converted: converted
        )
        var document = GesCodeDocument(
            header: header,
            prologue: prologue.text,
            space: spaceParts,
            swift: true,
            access: access,
            holds: "schema",
            parameters: !layout.parameters.isEmpty
        )
        document.extended = GesSchemaPlanner.extended(spaceParts, extended, modelParts)
        if let conversion {
            for (type, model) in conversions {
                document.units.append(GesCodeUnit(owner: type.name, write: { code in try modelConversionUnit(&code, type, model, access, conversion) }, outside: true))
            }
        }
        for type in types {
            if type.layout.packedWidth > 0 {
                if let packed {
                    document.units.append(
                        GesCodeUnit(owner: type.name) { code in
                            try GesSwiftModelEmitter.packedType(&code, packed, type.name, access, root: layout.roots.contains(type.name), values: context.values)
                        }
                    )
                }

                // A wire root's members extend the type at file scope where the wire code declares it, and are an enum
                // `<Name>Wire` in the wire namespace where the models declare it.
                let sharesModel = packed == nil
                let qualified = (sharesModel ? models : space) + type.name
                if layout.roots.contains(type.name) {
                    document.units.append(GesCodeUnit(owner: type.name, write: { code in packedRoot(&code, type, access, qualified, context, sharesModel) }, outside: !sharesModel))
                }
                continue
            }
            document.units.append(
                GesCodeUnit(owner: type.name) { code in
                    if type.kind == .messages { try messageSet(&code, type, access, context) } else { try record(&code, type, access, context) }
                }
            )
        }
        for set in sets {
            document.units.append(GesCodeUnit(owner: set.name) { code in tagSetDeclaration(&code, set.name, set.tags, access) })
        }
        for network in layout.networks {
            document.units.append(
                GesCodeUnit(owner: network.name) { code in
                    try self.network(&code, network, access, schemaSet?.qualified) { root in
                        // A packed root that the models declare has its wire members in an enum `<Name>Wire`.
                        let type = types.first { $0.name == root }!
                        let shared = type.layout.packedWidth > 0 && packed == nil
                        return NetworkRoot(type: shared ? models + root : root, wire: shared ? root + "Wire" : nil, plan: type)
                    }
                }
            )
        }
        try GesSchemaPlanner.checkTopLevel(context.topLevel, swift: true)
        // Split files reach the sources of another file, so the holder is internal there.
        let shared = options.split != .none
        if let setName = schemaSet?.declared {
            document.units.append(GesCodeUnit(owner: "") { code in GesSchemaSetReference.writeSwift(&code, setName, access, layout.sources, layout.parameters, networks: !layout.networks.isEmpty) })
        } else if options.values && schemaSet == nil {
            document.units.append(GesCodeUnit(owner: "", write: { code in valuesHolder(&code, layout, holder, shared: shared) }, outside: true))
        }
        if layout.types.contains(where: { !$0.computed.isEmpty }) {
            let computed = context.computed
            let values = computed.needsValues(types.map { ($0.name, $0.layout.computed) })
            let math = GesComputedEmitter.usesMath(types.map(\.layout.computed))
            let spatial = GesComputedEmitter.usesSpatial(types.map(\.layout.computed))
            document.units.append(GesCodeUnit(owner: "") { code in GesComputedLibrary.write(&code, computed.helper, swift: true, values: values, math: math, spatial: spatial) })
        }
        return document
    }

    // The keyed-list elements, and whether records convert to and from GES values through the helper type of the file.
    struct Context {
        let layout: GesSchemaLayout
        // The models that records convert to and from directly, nil without `--models`.
        let models: ModelConversion?
        let elements: Set<String>
        let values: Bool
        let holder: String
        // Whether the holder is a schema set, whose bind throws, rather than the private helper, which gives a Result.
        let schemaSet: Bool
        let checkedExclusivity: Bool
        let computed: GesComputedEmitter
        // The records and tag sets declared beside each other, which a record's nested type must not hide.
        let topLevel: Set<String>
        // The first components of the namespaces that a record names inside the wire namespace (inside) and that a converted
        // record's conversion names (converted), which the record's nested types must not hide.
        let inside: [String]
        let converted: [String]

        // The attribute of a class's stored properties: without exclusivity checks unless they are asked for.
        func stored(_ isClass: Bool) -> String { isClass && !checkedExclusivity ? "@exclusivity(unchecked) " : "" }
    }

    static func name(_ name: String) -> String { keywords.contains(name) ? "`" + name + "`" : name }

    static func member(_ pascal: String) -> String { name(GesSchemaPlanner.camel(pascal)) }

    static func kind(_ type: GesPlanType) -> String { type.kind == .message ? "message" : "schema" }

    static func record(_ code: inout Code, _ type: GesPlanType, _ access: String, _ context: Context) throws(GesGeneratorError) {
        var names: Names = []
        if !type.isItem {
            for name in reserved { names.append((name, "the generated member " + name)) }
        }
        if !type.isItem && context.values {
            for name in valueReserved { names.append((name, "the generated member " + name)) }
        }
        for field in type.fields {
            names.append((GesSchemaPlanner.camel(field.base), "the field " + field.layout.name))
            if field.optional { names.append(("has" + field.base, "the presence of " + field.layout.name)) }
            if field.optional && plain(field.value) { names.append((GesSchemaPlanner.camel(field.base) + "Optional", "the optional value of " + field.layout.name)) }
            nested(field.value, &names, field.layout.name)
        }
        for field in type.fields {
            if GesCSharpEmitter.isPooledList(field) { names.append(("set" + field.base + "Count", "the element count of " + field.layout.name)) }
            if GesCSharpEmitter.isTextList(field) { names.append((GesSchemaPlanner.camel(field.base) + "Values", "the texts of " + field.layout.name)) }
        }
        for tag in type.tags { names.append((GesSchemaPlanner.camel(tag.base), "the tag #" + tag.tag)) }
        if !type.isItem {
            for constant in type.layout.constants { names.append((constant.name, "the let " + constant.name)) }
        }
        if !type.isItem { GesComputedEmitter.names(type.layout.computed, type.name, swift: true, &names) }
        let model = type.isItem || type.kind != .schema ? nil : context.models?.type(type.name)
        if model != nil { names.append(("toModel", "the generated member toModel")) }
        try GesSchemaPlanner.unique(type.name, names, context.topLevel, hidden: model != nil ? context.converted : context.inside)

        code.line(type.isItem ? "/// An element of the list." : "/// The \(kind(type)) `:\(type.name)`, read and written without allocation\(type.isClass ? " once its storage has grown" : "").")
        code.open(type.isClass ? "\(access)final class \(type.name) {" : "\(access)struct \(type.name): Sendable {")
        if !type.isItem {
            constants(&code, type.layout, access)
            code.line("static let __paths: [String] = [")
            for path in type.paths { code.line("    " + GesSchemaPlanner.quote(path) + ",") }
            code.line("]")
        }
        let stored = context.stored(type.isClass)
        var first = type.isItem
        for field in type.fields {
            members(&code, field, access, stored, first)
            first = false
        }
        for tag in type.tags {
            code.line("/// Whether the tag `#\(tag.tag)` is set.")
            code.line("\(stored)\(access)var \(member(tag.base)) = false")
        }
        for field in type.fields { pools(&code, field.value, stored) }
        for field in type.fields { listAccess(&code, field, access) }
        if !type.isItem { context.computed.members(&code, type.name, type.layout.computed, String(access.dropLast(access.hasSuffix(" ") ? 1 : 0))) }
        code.blank()
        code.line(type.isItem ? "/// Creates an element with every field at its zero value." : "/// Creates a record with every field at its zero value.")
        code.line("\(access)init() {}")
        methods(&code, type, access)
        if type.isClass && (type.kind == .schema || type.isItem) { sharingMembers(&code, type, stored) }
        let deltas = type.kind == .schema && !type.isItem
        if deltas { sameHelpers(&code, type) }
        extras(&code, type, access, deltas, context.elements.contains(type.name))
        if context.values && !type.isItem { valueMembers(&code, type, access, context.holder, schemaSet: context.schemaSet) }
        for field in type.fields { try declarations(&code, field.value, access, context) }
        code.close()
    }

    static func constants(_ code: inout Code, _ layout: GesLayoutType, _ access: String) {
        code.line("/// The schema hash, independent of parameter values.")
        code.line("\(access)static let schemaHash: UInt64 = 0x\(GesSchemaLayoutJson.hex(layout.hash))")
        code.line("/// The hash over the schema hash and the parameter values this code was generated with.")
        code.line("\(access)static let bindingHash: UInt64 = 0x\(GesSchemaLayoutJson.hex(layout.bindingHash))")
        code.line("/// The size of the largest encoding in bytes.")
        code.line("\(access)static let maxByteCount = \(layout.maxByteCount)")
        lets(&code, layout.constants, access, "Int64")
    }

    /// The lets of a schema, in base units; a Percentage holds its ratio.
    static func lets(_ code: inout Code, _ constants: [GesLayoutConstant], _ access: String, _ integer: String) {
        for constant in constants {
            code.line("/// `\(GesSchemaPlanner.constantSource(constant))`")
            code.line("\(access)static let \(member(constant.name)): \(constant.integer ? integer : "Double") = \(GesSchemaPlanner.constantValue(constant))")
        }
    }

    static func plain(_ value: GesPlanValue) -> Bool { !value.isClass && value.encoding.kind != .union && value.encoding.kind != .text && value.encoding.kind != .bytes && value.encoding.kind != .list }

    // The byte storage of a Text or Bytes value in `owner`, "self" or another record.
    static func storage(_ value: GesPlanValue, _ owner: String) -> String {
        value.encoding.kind == .bytes ? "\(owner).\(member(value.base))" : "\(owner).\(GesSchemaPlanner.camel(value.base))UTF8"
    }

    static func nested(_ value: GesPlanValue, _ names: inout Names, _ field: String) {
        let name = nestedName(value)
        if !name.isEmpty && value.tagType.isEmpty { names.append((name, GesSchemaPlanner.nestedTypeOrigin + "of " + field)) }
        switch value.encoding.kind {
        case .text:
            names.append((GesSchemaPlanner.camel(value.base) + "UTF8", "the UTF-8 bytes of " + field))
        case .list:
            if value.encoding.poly { names.append((GesSchemaPlanner.camel(value.base) + "Poly", "the polygon view of " + field)) }
            if let item = value.item { names.append((item.name, GesSchemaPlanner.nestedTypeOrigin + "of the elements of " + field)) } else { nested(value.element!, &names, field) }
        case .union:
            for alternative in value.alternatives {
                if alternative.encoding.kind != .nothing { names.append((GesSchemaPlanner.camel(alternative.base), "the alternative \(alternative.label) of \(field)")) }
                nested(alternative, &names, field)
            }
        default:
            break
        }
    }

    static func nestedName(_ value: GesPlanValue) -> String {
        switch value.encoding.kind {
        case .tag: value.tagType.isEmpty ? value.base + "Tag" : value.tagType
        case .flags: value.base + "Flags"
        case .union: value.base + "Alternative"
        default: ""
        }
    }

    static func typeName(_ value: GesPlanValue) -> String {
        switch value.encoding.kind {
        case .boolean: "Bool"
        case .integer: "Int64"
        case .quantized, .float: "Double"
        case .schema: value.packed?.type ?? value.encoding.schema
        case .text: "String"
        case .bytes: "[UInt8]"
        case .point: "GesPoint"
        case .vector: "GesVector"
        case .box: "GesBox"
        case .disc: "GesDisc"
        case .list: "[\(elementName(value))]"
        default: nestedName(value)
        }
    }

    static func elementName(_ list: GesPlanValue) -> String { list.item?.name ?? typeName(list.element!) }

    // Sets a pooled list to a count of reused elements, as a read does, and for texts offers them as strings.
    static func listAccess(_ code: inout Code, _ field: GesPlanField, _ access: String) {
        if !GesCSharpEmitter.isPooledList(field) { return }
        let value = field.value
        let list = "self." + member(value.base)
        let pool = "self.__\(GesSchemaPlanner.camel(value.base))Pool"
        code.blank()
        code.line("/// Sets `\(field.layout.name)` to `count` elements that the record reuses, as a read does; their fields keep earlier values until they are set.")
        code.open("\(access)func set\(value.base)Count(_ count: Int) {")
        code.line("precondition(count >= 0, \"A count is not negative.\")")
        code.line("\(list).removeAll(keepingCapacity: true)")
        code.open("for position in 0..<count {")
        code.line("if position == \(pool).count { \(pool).append(\(elementName(value))()) }")
        code.line("\(list).append(\(pool)[position])")
        code.close()
        code.close()
        if !GesCSharpEmitter.isTextList(field) { return }
        let text = member(value.item!.fields[0].base)
        code.blank()
        code.line("/// The elements of `\(field.layout.name)` as strings; reading and setting allocate, and setting reuses the elements.")
        code.open("\(access)var \(GesSchemaPlanner.camel(value.base))Values: [String] {")
        code.line("get { \(list).map { $0.\(text) } }")
        code.open("set {")
        code.line("set\(value.base)Count(newValue.count)")
        code.line("for (index, text) in newValue.enumerated() { \(list)[index].\(text) = text }")
        code.close()
        code.close()
    }

    static func zero(_ value: GesPlanValue) -> String {
        switch value.encoding.kind {
        case .boolean: "false"
        case .integer: "0"
        case .quantized, .float: "0.0"
        case .tag: "." + name(value.encoding.tags[0])
        case .union: "." + member(value.alternatives[0].label)
        case .list, .bytes, .flags: "[]"
        case .box: "GesBox(GesPoint(), GesPoint())"
        case .disc: "GesDisc(radius: 0)"
        case .schema where value.packed != nil: typeName(value) + "(uncheckedRawValue: 0)"
        default: typeName(value) + "()"
        }
    }

    // `var` for a local that later code assigns, `let` for one it only reads, so that Swift warns about neither.
    static func binding(_ assigned: Bool) -> String { assigned ? "var" : "let" }

    static func members(_ code: inout Code, _ field: GesPlanField, _ access: String, _ stored: String, _ first: Bool) {
        if !first { code.blank() }
        if field.optional {
            code.line("/// Whether `\(field.layout.name)` is present.")
            code.line("\(stored)\(access)var has\(field.base) = false")
        }
        member(&code, field.value, "The field `\(field.layout.name)`", access, stored)
        if field.optional && plain(field.value) {
            let name = member(field.base)
            code.line("/// The field `\(field.layout.name)` as an optional value, nil when absent.")
            code.open("\(access)var \(GesSchemaPlanner.camel(field.base))Optional: \(typeName(field.value))? {")
            code.line("get { self.has\(field.base) ? self.\(name) : nil }")
            code.open("set {")
            code.line("self.has\(field.base) = newValue != nil")
            code.line("if let newValue { self.\(name) = newValue }")
            code.close()
            code.close()
        }
        if field.value.encoding.kind != .union { return }
        for alternative in field.value.alternatives where alternative.encoding.kind != .nothing {
            member(&code, alternative, "The value of `\(field.layout.name)` when its alternative is `\(alternative.label)`", access, stored)
        }
    }

    static func member(_ code: inout Code, _ value: GesPlanValue, _ summary: String, _ access: String, _ stored: String) {
        if value.encoding.kind != .text {
            code.line("/// \(summary)\(description(value)).")
            code.line("\(stored)\(access)var \(member(value.base)): \(typeName(value)) = \(zero(value))")
            if !value.encoding.poly { return }
            code.line("/// \(summary) as a polygon; reading it allocates.")
            code.line("\(access)var \(member(value.base + "Poly")): GesPoly { GesPoly(\(member(value.base))) }")
            return
        }
        let bytes = GesSchemaPlanner.camel(value.base) + "UTF8"
        code.line("/// \(summary) as UTF-8 bytes\(value.encoding.tagName ? ", a tag name without #" : ""), which are checked when the record is written.")
        code.line("\(stored)\(access)var \(bytes): [UInt8] = []")
        code.line("/// \(summary) as a string; reading and setting it allocate.")
        code.open("\(access)var \(member(value.base)): String {")
        code.line("get { String(decoding: self.\(bytes), as: UTF8.self) }")
        code.line("set { self.\(bytes) = Array(newValue.utf8) }")
        code.close()
    }

    // The instances a list of classes reuses when it is read again.
    static func pools(_ code: inout Code, _ value: GesPlanValue, _ stored: String) {
        if value.encoding.kind == .union {
            for alternative in value.alternatives { pools(&code, alternative, stored) }
        }
        if value.encoding.kind == .list && value.element!.isClass { code.line("\(stored)private var __\(GesSchemaPlanner.camel(value.base))Pool: [\(elementName(value))] = []") }
    }

    static func description(_ value: GesPlanValue) -> String {
        let encoding = value.encoding
        switch encoding.kind {
        case .quantized, .float, .integer, .point, .vector, .box, .disc: return encoding.unit != "none" ? ", in \(encoding.unit)" : ""
        case .union: return ", the selected alternative"
        case .list where encoding.poly: return ", the points of a polygon\(encoding.unit != "none" ? " in " + encoding.unit : ""), at most \(encoding.maxCount)"
        case .list: return ", at most \(encoding.maxCount) elements"
        default: return ""
        }
    }

    static func methods(_ code: inout Code, _ type: GesPlanType, _ access: String) {
        let mutating = type.isClass ? "" : "mutating "
        if !type.isItem {
            code.blank()
            publicMethods(&code, access, mutating, ["try __writeFields(&writer, Self.__paths, 0)"], ["try __readFields(&reader, Self.__paths, 0)"], "record")
            if let key = type.fields.first, key.key {
                code.blank()
                code.line("/// Reads the key, which comes first, before a caller chooses a baseline.")
                code.line("/// - Throws: `GesWireError` when the data ends before the key does or holds an invalid key.")
                code.open("\(access)static func readKey(from data: UnsafeRawBufferPointer) throws(GesWireError) -> \(typeName(key.value)) {")
                code.line("var reader = GesBitReader(data: data)")
                code.line("let paths = Self.__paths")
                code.line("let at = 0")
                code.line("var key: \(typeName(key.value)) = \(zero(key.value))")
                read(&code, key.value, "key")
                code.line("return key")
                code.close()
            }
        }
        code.blank()
        code.open("func __writeFields(_ writer: inout GesBitWriter, _ paths: [String], _ at: Int\(levelParameter(type))) throws(GesWireError) {")
        for field in type.fields {
            let target = "self." + member(field.base)
            if field.optional {
                code.open("if self.has\(field.base) {")
                code.line("try writer.write(1, width: 1)")
                write(&code, field.value, target)
                code.close("} else {")
                code.line("    try writer.write(0, width: 1)")
                code.line("}")
            } else {
                write(&code, field.value, target)
            }
        }
        for tag in type.tags { code.line("try writer.write(self.\(member(tag.base)) ? 1 : 0, width: 1)") }
        code.close()
        code.blank()
        code.open("\(mutating)func __readFields(_ reader: inout GesBitReader, _ paths: [String], _ at: Int\(levelParameter(type))) throws(GesWireError) {")
        for field in type.fields {
            let target = "self." + member(field.base)
            if field.optional {
                code.line("self.has\(field.base) = try reader.read(1, path: \(path(field.value))) != 0")
                code.open("if self.has\(field.base) {")
                read(&code, field.value, target)
                if plain(field.value) {
                    code.close("} else {")
                    code.line("    \(target) = \(zero(field.value))")
                    code.line("}")
                } else {
                    code.close()
                }
            } else {
                read(&code, field.value, target)
            }
        }
        for tag in type.tags { code.line("self.\(member(tag.base)) = try reader.read(1, path: paths[at + \(tag.node)]) != 0") }
        code.close()
    }

    static func publicMethods(_ code: inout Code, _ access: String, _ mutating: String, _ write: [String], _ read: [String], _ what: String) {
        code.line("/// Writes this \(what) into a buffer; `maxByteCount` bytes always suffice.")
        code.line("/// - Returns: The number of bytes written.")
        code.line("/// - Throws: `GesWireError` when a value does not fit its field or the buffer is too small.")
        code.open("\(access)func write(into buffer: UnsafeMutableRawBufferPointer) throws(GesWireError) -> Int {")
        code.line("var writer = GesBitWriter(into: buffer)")
        for line in write { code.line(line) }
        code.line("return try writer.finish()")
        code.close()
        code.blank()
        code.line("/// Counts the bytes that `write(into:)` writes for this \(what), without writing them.")
        code.line("/// - Throws: `GesWireError` when a value does not fit its field.")
        code.open("\(access)func encodedByteCount() throws(GesWireError) -> Int {")
        code.line("var writer = GesBitWriter.counting()")
        for line in write { code.line(line) }
        code.line("return try writer.finish()")
        code.close()
        code.blank()
        code.line("/// Writes this \(what) into a new array of its exact size, which `encodedByteCount()` counts first.")
        code.line("/// - Throws: `GesWireError` when a value does not fit its field.")
        code.open("\(access)func encoded() throws(GesWireError) -> [UInt8] {")
        code.line("let buffer = UnsafeMutableRawBufferPointer.allocate(byteCount: Swift.max(try encodedByteCount(), 1), alignment: 8)")
        code.line("defer { buffer.deallocate() }")
        code.line("let count = try write(into: buffer)")
        code.line("return Array(buffer[0..<count])")
        code.close()
        code.blank()
        code.line("/// Reads a \(what) from untrusted data into this instance. After an error its values are unspecified.")
        code.line("/// - Parameters:")
        code.line("///   - data: The data; it may continue after the record.")
        code.line("///   - byteLimit: An optional limit on the bytes of this record.")
        code.line("/// - Returns: The number of bytes the record occupies.")
        code.line("/// - Throws: `GesWireError` when the data is no valid \(what).")
        code.line("@discardableResult")
        code.open("\(access)\(mutating)func read(from data: UnsafeRawBufferPointer, byteLimit: Int = .max) throws(GesWireError) -> Int {")
        code.line("var reader = GesBitReader(data: data, byteLimit: byteLimit)")
        for line in read { code.line(line) }
        code.line("return try reader.finish()")
        code.close()
        code.blank()
        code.line("/// Reads a \(what) from bytes into this instance. After an error its values are unspecified.")
        code.line("/// - Returns: The number of bytes the record occupies.")
        code.line("/// - Throws: `GesWireError` when the bytes are no valid \(what).")
        code.line("@discardableResult")
        code.open("\(access)\(mutating)func read(from bytes: [UInt8], byteLimit: Int = .max) throws(GesWireError) -> Int {")
        code.line("let buffer = UnsafeMutableRawBufferPointer.allocate(byteCount: Swift.max(bytes.count, 1), alignment: 8)")
        code.line("defer { buffer.deallocate() }")
        code.line("buffer.copyBytes(from: bytes)")
        code.line("return try read(from: UnsafeRawBufferPointer(rebasing: buffer[0..<bytes.count]), byteLimit: byteLimit)")
        code.close()
    }

    static func messageSet(_ code: inout Code, _ type: GesPlanType, _ access: String, _ context: Context) throws(GesGeneratorError) {
        var names: Names = [
            ("selected", "the selected member"), ("Member", GesSchemaPlanner.nestedTypeOrigin + "of the members"), ("Case", GesSchemaPlanner.nestedTypeOrigin + "of the messages"),
            ("asCase", "the generated member asCase"), ("assign", "the generated member assign"),
        ]
        for name in reserved { names.append((name, "the generated member " + name)) }
        if context.values {
            for name in valueReserved { names.append((name, "the generated member " + name)) }
        }
        for member in type.members { names.append((GesSchemaPlanner.camel(member), "the member " + member)) }
        try GesSchemaPlanner.unique(type.name, names, context.topLevel)
        let width = String(type.layout.memberWidth)
        let last = String(UInt64(type.members.count) - 1)
        code.line("/// The message set `:\(type.name)`: one of its messages, read and written without allocation\(type.membersAreClasses ? " once its storage has grown" : "").")
        code.open(type.membersAreClasses ? "\(access)final class \(type.name) {" : "\(access)struct \(type.name): Sendable {")
        constants(&code, type.layout, access)
        code.line("/// The message this record holds.")
        let stored = context.stored(type.membersAreClasses)
        code.line("\(stored)\(access)var selected: Member = .\(member(type.members[0]))")
        for name in type.members {
            code.line("/// The message when `selected` is `\(GesSchemaPlanner.camel(name))`.")
            code.line("\(stored)\(access)var \(member(name)) = \(name)()")
        }
        code.blank()
        code.line("/// Creates a record that holds the first message, with every field at its zero value.")
        code.line("\(access)init() {}")
        var write = ["try writer.write(UInt64(self.selected.rawValue), width: \(width))", "switch self.selected {"]
        var read = ["let index = try reader.read(\(width), path: \"\")"]
        if UInt64(type.members.count) - 1 < full(type.layout.memberWidth) { read.append("if index > \(last) { throw GesWireError(code: GesWireError.invalidIndex, path: \"\") }") }
        read += ["self.selected = Member(rawValue: \(underlying(type.members.count))(index))!", "switch self.selected {"]
        for name in type.members {
            write += ["case .\(member(name)):", "    try self.\(member(name)).__writeFields(&writer, \(name).__paths, 0)"]
            read += ["case .\(member(name)):", "    try self.\(member(name)).__readFields(&reader, \(name).__paths, 0)"]
        }
        write.append("}")
        read.append("}")
        code.blank()
        publicMethods(&code, access, type.membersAreClasses ? "" : "mutating ", write, read, "message")
        if context.values { valueMembers(&code, type, access, context.holder, schemaSet: context.schemaSet) }
        messageCases(&code, type, access)
        code.blank()
        code.line("/// The messages of the set, in declared order.")
        code.open("\(access)enum Member: \(underlying(type.members.count)), Sendable {")
        for name in type.members {
            code.line("/// The message `\(name)`.")
            code.line("case \(member(name))")
        }
        code.close()
        code.close()
    }

    // The message of a set as an enum with one case per member, holding that member's record, and the conversions both ways.
    static func messageCases(_ code: inout Code, _ type: GesPlanType, _ access: String) {
        code.blank()
        code.line("/// The selected message as a case.")
        code.open("\(access)var asCase: Case {")
        code.line("switch selected {")
        for name in type.members { code.line("case .\(member(name)): .\(member(name))(self.\(member(name)))") }
        code.line("}")
        code.close()
        code.blank()
        code.line("/// Selects the message of a case and stores its record.")
        code.line("/// - Parameter value: The message.")
        code.open("\(access)\(type.membersAreClasses ? "" : "mutating ")func assign(_ value: Case) {")
        code.line("switch value {")
        for name in type.members {
            code.line("case .\(member(name))(let value):")
            code.line("    selected = .\(member(name))")
            code.line("    self.\(member(name)) = value")
        }
        code.line("}")
        code.close()
        code.blank()
        code.line("/// A message of the set as a value: one case per message, holding its record.")
        code.open("\(access)enum Case\(type.membersAreClasses ? "" : ": Sendable") {")
        for name in type.members {
            code.line("/// The message `\(name)`.")
            code.line("case \(member(name))(\(name))")
        }
        code.close()
    }

    static func path(_ value: GesPlanValue) -> String { "paths[at + \(value.node)]" }

    // A recursive schema's methods take the level of the record, 1 where a caller enters the recursion.
    static func levelParameter(_ type: GesPlanType) -> String { type.depth > 0 ? ", _ level: Int = 1" : "" }

    // The level argument of a call into a record: one deeper for the element of a recursive List.
    static func nextLevel(_ value: GesPlanValue) -> String { value.recursive ? ", level + 1" : "" }

    // The level that the item of a recursive union takes: that of the record holding the List.
    static func itemLevel(_ element: GesPlanValue) -> String { element.passesLevel ? ", level" : "" }

    // Opens the levels of a recursive List that hold elements; at its depth the List holds nothing, so data there is deeper.
    static func openLevels(_ code: inout Code, _ value: GesPlanValue, _ count: String) {
        code.open("if level >= \(value.depth) {")
        code.line("if \(count) > 0 { throw GesWireError(code: GesWireError.tooDeep, path: \(path(value)), detail: \"deeper than depth \(value.depth)\") }")
        code.close("} else {")
        code.indent()
    }

    static func fail(_ code: String, _ value: GesPlanValue) -> String { "throw GesWireError(code: GesWireError.\(code), path: \(path(value)))" }

    static func write(_ code: inout Code, _ value: GesPlanValue, _ target: String) {
        let encoding = value.encoding
        let width = String(encoding.width)
        let max = String(encoding.maxCount)
        switch encoding.kind {
        case .boolean:
            code.line("try writer.write(\(target) ? 1 : 0, width: 1)")
        case .integer where !encoding.range:
            code.line("try writer.write(UInt64(bitPattern: \(target)), width: 64)")
        case .integer where encoding.wrapping:
            code.line("try writer.write(GesWireRules.wrappedIndex(\(target), lower: \(long(encoding.lower)), period: \(encoding.maxIndex &+ 1)), width: \(width))")
        case .integer:
            let lower = String(UInt64(bitPattern: encoding.lower))
            code.line("if \(target) < \(long(encoding.lower)) || UInt64(bitPattern: \(target)) &- \(lower) > \(encoding.maxIndex) { \(fail("outOfRange", value)) }")
            code.line("try writer.write(UInt64(bitPattern: \(target)) &- \(lower), width: \(width))")
        case .quantized where encoding.wrapping:
            code.line("try writer.write(")
            code.line(
                "    try GesWireRules.wrappedQuantizedIndex(\(target), tenPower: \(double(encoding.tenPower)), numerator: \(double(encoding.numerator)), lower: \(long(encoding.lower)), period: \(encoding.maxIndex &+ 1), path: \(path(value))),"
            )
            code.line("    width: \(width)")
            code.line(")")
        case .quantized:
            code.line("try writer.write(")
            code.line(
                "    try GesWireRules.quantizedIndex(\(target), lowerValue: \(bits(encoding.lowerValue)), upperValue: \(bits(encoding.upperValue)), tenPower: \(double(encoding.tenPower)), numerator: \(double(encoding.numerator)), lower: \(long(encoding.lower)), path: \(path(value))),"
            )
            code.line("    width: \(width)")
            code.line(")")
        case .float:
            code.line("if \(target).isNaN { \(fail("notRepresentable", value)) }")
            if encoding.range { code.line("if \(target) < \(bits(encoding.lowerValue)) || \(target) > \(bits(encoding.upperValue)) { \(fail("outOfRange", value)) }") }
            code.line("try writer.write((\(target) == 0 ? 0.0 : \(target)).bitPattern, width: 64)")
        case .tag:
            code.line("try writer.write(UInt64(\(target).rawValue), width: \(width))")
        case .flags:
            if encoding.width < 64 { code.line("if \(target).rawValue > \(full(encoding.width)) { \(fail("unknownTag", value)) }") }
            code.line("try writer.write(\(target).rawValue, width: \(width))")
        case .text, .bytes:
            let bytes = storage(value, "self")
            code.line("if \(bytes).count > \(max) { \(fail("tooLong", value)) }")
            if encoding.kind == .text {
                code.line(
                    encoding.tagName
                        ? "if !\(bytes).withUnsafeBytes({ GesWireRules.isTagName($0) }) { \(fail("invalidTag", value)) }"
                        : "if !\(bytes).withUnsafeBytes({ GesWireRules.isValidUTF8($0) }) { \(fail("invalidText", value)) }"
                )
            }
            code.line("try writer.write(UInt64(\(bytes).count), width: \(width))")
            code.line("try writer.writeBytes(\(bytes))")
        case .list:
            if value.depth > 0 { openLevels(&code, value, target + ".count") }
            code.line("if \(target).count > \(max) { \(fail("tooLong", value)) }")
            code.line("try writer.write(UInt64(\(target).count), width: \(width))")
            code.open("for item in \(target) {")
            if value.item != nil {
                code.line("try item.__writeFields(&writer, paths, at + \(value.element!.node)\(itemLevel(value.element!)))")
            } else {
                write(&code, value.element!, "item")
            }
            code.close()
            if value.depth > 0 { code.close() }
        case .point, .vector:
            for axis in value.axes { write(&code, axis, target + "." + member(axis.base)) }
            for axis in GesSchemaPlanner.omitted(value) { code.line("if \(target).\(member(axis)) != 0 { \(fail("typeMismatch", value)) }") }
        case .box:
            for corner in value.corners { write(&code, corner, target + "." + member(corner.base)) }
        case .disc:
            for part in value.corners { write(&code, part, target + "." + member(part.base)) }
            if value.corners.count == 1 { code.line("if \(target).radius != 0 { \(fail("typeMismatch", value)) }") }
        case .schema where value.packed != nil:
            packedWrite(&code, value, target)
        case .schema:
            code.line("try \(target).__writeFields(&writer, paths, at + \(value.node + 1)\(nextLevel(value)))")
        case .union:
            code.line("switch \(target) {")
            for (index, alternative) in value.alternatives.enumerated() {
                code.open("case .\(member(alternative.label)):")
                code.line("try writer.write(\(index), width: \(width))")
                if alternative.encoding.kind != .nothing { write(&code, alternative, "self." + member(alternative.base)) }
                code.close("")
            }
            code.line("}")
        case .nothing:
            break
        }
    }

    static func read(_ code: inout Code, _ value: GesPlanValue, _ target: String) {
        let encoding = value.encoding
        let width = String(encoding.width)
        let max = String(encoding.maxCount)
        switch encoding.kind {
        case .boolean:
            code.line("\(target) = try reader.read(1, path: \(path(value))) != 0")
        case .integer where !encoding.range:
            code.line("\(target) = Int64(bitPattern: try reader.read(64, path: \(path(value))))")
        case .flags:
            code.line("\(target) = \(nestedName(value))(rawValue: try reader.read(\(width), path: \(path(value))))")
        case .integer, .quantized, .tag:
            code.open("do {")
            code.line("let index = try reader.read(\(width), path: \(path(value)))")
            let largest = encoding.kind == .tag ? UInt64(encoding.tags.count) - 1 : encoding.maxIndex
            if largest < full(encoding.width) { code.line("if index > \(largest) { \(fail("invalidIndex", value)) }") }
            switch encoding.kind {
            case .integer: code.line("\(target) = Int64(bitPattern: \(UInt64(bitPattern: encoding.lower)) &+ index)")
            case .quantized:
                code.line("\(target) = GesWireRules.quantizedValue(index, lower: \(long(encoding.lower)), numerator: \(long(encoding.numerator)), tenPower: \(double(encoding.tenPower)))")
            default: code.line("\(target) = \(nestedName(value))(rawValue: \(underlying(encoding.tags.count))(index))!")
            }
            code.close()
        case .float:
            code.open("do {")
            code.line("let bits = try reader.read(64, path: \(path(value)))")
            code.line("let value = Double(bitPattern: bits)")
            code.line("if value.isNaN || bits == 0x8000_0000_0000_0000\(encoding.range ? " || value.isInfinite" : "") { \(fail("invalidNumber", value)) }")
            if encoding.range { code.line("if value < \(bits(encoding.lowerValue)) || value > \(bits(encoding.upperValue)) { \(fail("outOfRange", value)) }") }
            code.line("\(target) = value")
            code.close()
        case .text, .bytes:
            let bytes = storage(value, "self")
            code.open("do {")
            code.line("let count = Int(try reader.read(\(width), path: \(path(value))))")
            code.line("if count > \(max) { \(fail("invalidCount", value)) }")
            code.line("try reader.readBytes(count, into: &\(bytes), path: \(path(value)))")
            if encoding.kind == .text {
                code.line(
                    encoding.tagName
                        ? "if !\(bytes).withUnsafeBytes({ GesWireRules.isTagName($0) }) { \(fail("invalidTag", value)) }"
                        : "if !\(bytes).withUnsafeBytes({ GesWireRules.isValidUTF8($0) }) { \(fail("invalidText", value)) }"
                )
            }
            code.close()
        case .list:
            let element = value.element!
            let name = elementName(value)
            if value.depth > 0 {
                // The deepest level reads no count, since its List takes no bits.
                code.open("if level >= \(value.depth) {")
                code.line("\(target).removeAll(keepingCapacity: true)")
                code.close("} else {")
                code.indent()
            } else {
                code.open("do {")
            }
            code.line("let count = Int(try reader.read(\(width), path: \(path(value))))")
            code.line("if count > \(max) { \(fail("invalidCount", value)) }")
            code.line("\(target).removeAll(keepingCapacity: true)")
            if element.packed != nil {
                packedList(&code, value, target, "count")
                code.close()
                break
            }
            code.open(element.isClass ? "for position in 0..<count {" : "for _ in 0..<count {")
            if element.isClass {
                let pool = "self.__\(GesSchemaPlanner.camel(value.base))Pool"
                code.line("if position == \(pool).count { \(pool).append(\(name)()) }")
                code.line("let item = \(pool)[position]")
            } else if value.item != nil || element.encoding.kind == .point || element.encoding.kind == .vector || element.encoding.kind == .schema {
                code.line(value.item != nil ? "var item = \(name)()" : "var item = \(zero(element))")
            } else {
                code.line("var item: \(name) = \(zero(element))")
            }
            if value.item != nil {
                code.line("try item.__readFields(&reader, paths, at + \(element.node)\(itemLevel(element)))")
            } else {
                read(&code, element, "item")
            }
            code.line("\(target).append(item)")
            code.close()
            code.close()
        case .point, .vector:
            for axis in value.axes { read(&code, axis, target + "." + member(axis.base)) }
            for axis in GesSchemaPlanner.omitted(value) { code.line("\(target).\(member(axis)) = 0") }
        case .box:
            // The corners arrive as two Points; the box orders them.
            code.open("do {")
            for corner in value.corners {
                code.line("var \(corner.label)\(value.node) = GesPoint()")
                read(&code, corner, corner.label + String(value.node))
            }
            code.line("\(target) = GesBox(lower\(value.node), upper\(value.node))")
            code.close()
        case .disc:
            // The centre and the radius, which a block can leave out; the disc takes the radius's magnitude.
            code.open("do {")
            code.line("var center\(value.node) = GesPoint()")
            code.line("\(binding(value.corners.count > 1)) radius\(value.node) = 0.0")
            for part in value.corners { read(&code, part, part.label + String(value.node)) }
            code.line("\(target) = GesDisc(center: center\(value.node), radius: radius\(value.node))")
            code.close()
        case .schema where value.packed != nil:
            packedRead(&code, value, target)
        case .schema:
            code.line("try \(target).__readFields(&reader, paths, at + \(value.node + 1)\(nextLevel(value)))")
        case .union:
            code.open("do {")
            code.line("let choice = try reader.read(\(width), path: \(path(value)))")
            let largest = UInt64(value.alternatives.count) - 1
            if largest < full(encoding.width) { code.line("if choice > \(largest) { \(fail("invalidIndex", value)) }") }
            code.line("\(target) = \(nestedName(value))(rawValue: \(underlying(value.alternatives.count))(choice))!")
            code.line("switch choice {")
            for (index, alternative) in value.alternatives.enumerated() where alternative.encoding.kind != .nothing {
                code.open("case \(index):")
                read(&code, alternative, "self." + member(alternative.base))
                code.close("")
            }
            code.open("default:")
            code.line("break")
            code.close("}")
            code.close()
        case .nothing:
            break
        }
    }

    static func declarations(_ code: inout Code, _ value: GesPlanValue, _ access: String, _ context: Context) throws(GesGeneratorError) {
        let name = nestedName(value)
        switch value.encoding.kind {
        case .tag:
            if !value.tagType.isEmpty { break }
            code.blank()
            code.line("/// The tags of the field, in declared order.")
            code.open("\(access)enum \(name): \(underlying(value.encoding.tags.count)), Sendable {")
            for tag in value.encoding.tags {
                code.line("/// The tag `#\(tag)`.")
                code.line("case \(self.name(tag))")
            }
            code.close()
        case .flags:
            try flagsDeclaration(&code, name, value.encoding.tags, access)
        case .union:
            code.blank()
            code.line("/// The alternatives of the field, in declared order.")
            code.open("\(access)enum \(name): \(underlying(value.alternatives.count)), Sendable {")
            for alternative in value.alternatives {
                code.line("/// The alternative `:\(alternative.label)`.")
                code.line("case \(member(alternative.label))")
            }
            code.close()
            for alternative in value.alternatives { try declarations(&code, alternative, access, context) }
        case .list:
            if let item = value.item {
                code.blank()
                try record(&code, item, access, context)
            } else {
                try declarations(&code, value.element!, access, context)
            }
        default:
            break
        }
    }

    static func underlying(_ count: Int) -> String { count <= 256 ? "UInt8" : count <= 65536 ? "UInt16" : "UInt32" }

    // The root of a route: its type, and for a packed root the models declare, the enum `<Name>Wire` of its wire members.
    struct NetworkRoot {
        let type: String
        let wire: String?
        let plan: GesPlanType

        var isSet: Bool { plan.kind == .messages }

        // The type whose `maxByteCount` bounds an encoding.
        var owner: String { wire ?? type }

        func write(_ value: String, _ buffer: String) -> String { wire.map { "\($0).write(\(value), into: \(buffer))" } ?? "\(value).write(into: \(buffer))" }

        func read(_ record: String, _ data: String) -> String { wire.map { "\($0).read(&\(record), from: \(data))" } ?? "\(record).read(from: \(data))" }

        var initial: String { wire == nil ? type + "()" : type + "(uncheckedRawValue: 0)" }
    }

    // The constants of a network, its hash, the index of each route and the rate of each topic that has one, and a
    // function per route that encodes its root and sends or publishes it.
    static func network(_ code: inout Code, _ network: GesLayoutNetwork, _ access: String, _ schemaSet: String?, _ roots: (String) -> NetworkRoot) throws(GesGeneratorError) {
        code.line("/// The network `:\(network.name)`: its hash, the index of each route, the rate of each topic that has one and a typed function per route.")
        code.open("\(access)enum \(network.name) {")
        code.line("/// The network hash over the routes and their bound roots, which the handshake compares.")
        code.line("\(access)static let hash: UInt64 = 0x\(GesSchemaLayoutJson.hex(network.hash))")
        if let schemaSet {
            code.blank()
            code.line("private static let __bound = Result<GesBoundNetwork, any Error> { try \(schemaSet).bindNetwork(\(GesSchemaPlanner.literal(network.name, swift: true)), hash: hash) }")
            code.blank()
            code.line("/// The network bound with the parameters of the schema set, checked against `hash` on first access.")
            code.line("/// - Throws: `GesSchemaError` when the sources no longer parse or the network no longer binds, and `\(schemaSet).Mismatch` when the bound network hash differs.")
            code.open("\(access)static var bound: GesBoundNetwork {")
            code.line("get throws { try __bound.get() }")
            code.close()
        }
        for route in network.routes {
            let name = GesSchemaPlanner.camel(route.name)
            code.blank()
            code.line("/// The index of the route `\(route.side) \(route.verb) :\(route.root) \(route.deliveryClass)`.")
            code.line("\(access)static let \(name) = \(route.index)")
            if route.rateMicroseconds == 0 { continue }
            code.blank()
            code.line("/// The shortest interval between two updates of the topic `:\(route.root)` in microseconds.")
            code.line("\(access)static let \(name)EveryMicroseconds: Int64 = \(route.rateMicroseconds)")
        }
        for route in network.routes {
            let publishes = route.verb == "publishes"
            let verb = publishes ? "publish" : "send"
            let root = roots(route.root)
            let type = root.type
            let write = root.write("value", "buffer")
            code.blank()
            code.line("/// Encodes a record into a buffer and \(publishes ? "publishes" : "sends") it on the route `\(route.side) \(route.verb) :\(route.root) \(route.deliveryClass)`.")
            code.line("/// - Parameters:")
            code.line("///   - value: The record.")
            code.line("///   - connection: The \(route.side)'s connection.")
            code.line("///   - buffer: The buffer the record is encoded into; its `maxByteCount` bytes always suffice.")
            code.line("/// - Returns: The status of `GesNetworkConnection.\(verb)(route:payload:)`.")
            code.line("/// - Throws: `GesWireError` when a value does not fit its field or the buffer is too small.")
            code.open("\(access)static func \(route.side)\(GesSchemaPlanner.pascal(verb))\(route.root)(_ value: \(type), on connection: GesNetworkConnection, buffer: UnsafeMutableRawBufferPointer) throws(GesWireError) -> GesNetworkSendStatus {")
            code.line("let count = try \(write)")
            code.line("return connection.\(verb)(route: \(GesSchemaPlanner.camel(route.name)), payload: UnsafeRawBufferPointer(rebasing: buffer[..<count]))")
            code.close()
        }
        for client in [true, false] {
            let end = try GesNetworkEndPlan.plan(network, client: client)
            typedEnd(&code, network, end, access, roots)
            endEvent(&code, network, end, access, roots)
        }
        code.close()
    }

    // A typed end: it encodes the roots of its side into one buffer, reads the roots it receives into one record per route
    // and hands them to the closure of a poll as events.
    static func typedEnd(_ code: inout Code, _ network: GesLayoutNetwork, _ end: GesNetworkEndPlan, _ access: String, _ roots: (String) -> NetworkRoot) {
        let isClient = end.client
        let endType = isClient ? "GesNetworkClientEnd" : "GesNetworkServerEnd"
        let eventType = end.name + "Event"
        let side = isClient ? "client" : "server"
        let net = network.name

        // Distinct prefixes keep the scratch record of an outgoing message set apart from the record of each received route.
        func field(_ name: String) -> String { "__" + GesSchemaPlanner.camel(name) }

        func outgoing(_ route: GesLayoutRoute) -> String { "__out_" + GesSchemaPlanner.camel((route.verb == "sends" ? "Send" : "Publish") + route.root) }

        func routeName(_ route: GesLayoutRoute) -> String { net + "." + GesSchemaPlanner.camel(route.name) }

        func caseName(_ name: String) -> String { self.name(GesSchemaPlanner.camel(name)) }

        code.blank()
        code.line("/// The typed \(side) end of `:\(net)`: it encodes the records the \(side) sends and publishes and hands the records it receives")
        code.line("/// to the closure of `poll(_:)` as `\(eventType)` values. A received record that is a class is borrowed: it stays valid until")
        code.line("/// the closure returns.")
        code.open("\(access)final class \(end.name) {")
        code.line("/// The wrapped end.")
        code.line("\(access)let end: \(endType)")
        code.line("private let __buffer: UnsafeMutableRawBufferPointer")
        for route in end.outgoing {
            let root = roots(route.root)
            if root.isSet { code.line("private var \(outgoing(route)) = \(root.initial)") }
        }
        for (route, name) in end.incoming { code.line("private var \(field(name)) = \(roots(route.root).initial)") }
        code.blank()
        code.line("/// Wraps an end of the network.")
        code.line("/// - Parameter end: The end; its bound network must have the hash `\(net).hash`.")
        code.line("/// - Throws: `GesApiError.invalidArgument` when the end's network has another hash.")
        code.open("\(access)init(_ end: \(endType)) throws {")
        code.line("guard end.network.hash == \(net).hash else { throw GesApiError.invalidArgument(\"The end's network is no :\(net).\") }")
        code.line("self.end = end")
        var sizes: [String] = []
        for route in end.outgoing {
            let owner = roots(route.root).owner + ".maxByteCount"
            if !sizes.contains(owner) { sizes.append(owner) }
        }
        let size = sizes.count == 0 ? "0" : sizes.count == 1 ? sizes[0] : "max(\(sizes.joined(separator: ", ")))"
        code.line("__buffer = .allocate(byteCount: \(size), alignment: 1)")
        code.close()
        code.blank()
        code.line("deinit { __buffer.deallocate() }")
        if isClient {
            code.blank()
            code.line("/// The end's connection.")
            code.line("\(access)var connection: GesNetworkConnection { end.connection }")
        } else {
            code.blank()
            code.line("/// The number of connecting and connected clients.")
            code.line("\(access)var clientCount: Int { end.clientCount }")
            code.blank()
            code.line("/// Returns the connection of a client.")
            code.line("/// - Parameter client: The client.")
            code.line("/// - Throws: `GesApiError.invalidArgument` when the client is not connected to the end.")
            code.line("\(access)func connection(client: Int) throws -> GesNetworkConnection { try end.connection(client: client) }")
        }
        for route in end.outgoing {
            let root = roots(route.root)
            let publishes = route.verb == "publishes"
            let verb = publishes ? "publish" : "send"
            let what = "`\(route.side) \(route.verb) :\(route.root) \(route.deliveryClass)`"
            var targets: [(parameters: String, arguments: String, doc: String)] = [("", "", publishes ? "to the subscribed clients" : isClient ? "to the server" : "to every client")]
            if !isClient && !publishes { targets.append((", client: Int", ", client: client", "to one client")) }
            for (parameters, arguments, doc) in targets {
                let toClient = !arguments.isEmpty
                let throwing = toClient ? "throws" : "throws(GesWireError)"
                let label = "\(endType).\(verb)(route:payload:\(toClient ? "client:" : ""))"
                let failure = "/// - Throws: `GesWireError` when a value does not fit its field\(toClient ? "; `GesApiError.invalidArgument` when the client is not connected to the end" : "")."
                code.blank()
                code.line("/// Encodes a record and \(publishes ? "publishes" : "sends") it on the route \(what)\(isClient ? "" : ", " + doc).")
                self.parameters(&code, toClient, "The record.")
                code.line("/// - Returns: The status of `\(label)`.")
                code.line(failure)
                code.line("@discardableResult")
                code.open("\(access)func \(verb)(_ value: \(root.type)\(parameters)) \(throwing) -> GesNetworkSendStatus {")
                code.line("let count = try \(root.write("value", "__buffer"))")
                code.line("return \(toClient ? "try " : "")end.\(verb)(route: \(routeName(route)), payload: UnsafeRawBufferPointer(rebasing: __buffer[..<count])\(arguments))")
                code.close()
                if !root.isSet { continue }
                code.blank()
                code.line("/// Encodes a message and \(publishes ? "publishes" : "sends") it on the route \(what)\(isClient ? "" : ", " + doc).")
                self.parameters(&code, toClient, "The message.")
                code.line("/// - Returns: The status of `\(label)`.")
                code.line(failure)
                code.line("@discardableResult")
                code.open("\(access)func \(verb)(_ value: \(root.type).Case\(parameters)) \(throwing) -> GesNetworkSendStatus {")
                code.line("\(outgoing(route)).assign(value)")
                code.line("return try \(verb)(\(outgoing(route))\(arguments))")
                code.close()
            }
        }
        if !isClient {
            code.blank()
            code.line("/// Refuses a connecting client; call it while the closure of `poll(_:)` handles its `connecting` event.")
            code.line("/// - Parameters:")
            code.line("///   - client: The client.")
            code.line("///   - detail: The detail sent to the client.")
            code.line("/// - Throws: `GesApiError.invalidArgument` when the client is not connected to the end.")
            code.line("\(access)func refuse(client: Int, detail: String) throws { try end.refuse(client: client, detail: detail) }")
            code.blank()
            code.line("/// Closes the connection of one client with a detail.")
            code.line("/// - Parameters:")
            code.line("///   - client: The client.")
            code.line("///   - detail: The detail sent to the client.")
            code.line("/// - Throws: `GesApiError.invalidArgument` when the client is not connected to the end.")
            code.line("\(access)func close(client: Int, detail: String) throws { try end.close(client: client, detail: detail) }")
        }
        code.blank()
        code.line(isClient ? "/// Closes the connection with a detail." : "/// Closes every current connection with a detail; the end still accepts new clients.")
        code.line("/// - Parameter detail: The detail sent to the \(isClient ? "server" : "clients").")
        code.line("\(access)func close(_ detail: String) { end.close(detail) }")
        if end.hasTopics { tickMembers(&code, end, access, roots) }
        code.blank()
        code.line("/// Polls the end and hands every event to the closure. Never blocks.")
        code.line("/// - Parameter handler: The closure; a received record that is a class stays valid until it returns.")
        code.line("/// - Throws: `GesApiError.invalidOperation` when the end is released or polled already; an error of a link or the closure.")
        code.open("\(access)func poll(_ handler: (\(eventType)) throws -> Void) throws {")
        code.line("try end.poll { event in try self.__handle(event, handler) }")
        code.close()
        code.blank()
        code.open("private func __handle(_ event: GesNetworkEndEvent, _ handler: (\(eventType)) throws -> Void) throws {")
        let client = isClient ? "" : "client: event.client, "
        code.line("switch event.kind {")
        if isClient {
            code.line("case .connected:")
            code.line("    try handler(.connected(security: event.security))")
            code.line("case .disconnected:")
            code.line("    try handler(.disconnected(code: event.code, detail: event.detail, byPeer: event.byPeer))")
        } else {
            code.line("case .connecting:")
            code.line("    try handler(.connecting(client: event.client, token: event.payload))")
            code.line("case .clientConnected:")
            code.line("    try handler(.clientConnected(client: event.client, security: event.security))")
            code.line("case .clientDisconnected:")
            code.line("    try handler(.clientDisconnected(client: event.client, code: event.code, detail: event.detail, byPeer: event.byPeer))")
        }
        if !end.incoming.isEmpty {
            code.line("case .message:")
            code.line("    switch event.route {")
            for (route, name) in end.incoming {
                let root = roots(route.root)
                let record = field(name)
                code.line("    case \(routeName(route)):")
                code.line("        do {")
                code.line("            _ = try \(root.read(record, "event.payload"))")
                code.line("        } catch {")
                code.line("            \(isClient ? "" : "try ")end.close(\(isClient ? "" : "client: event.client, detail: ")\"undecodable :\(route.root)\")")
                code.line("            return")
                code.line("        }")
                code.line("        try handler(.\(caseName(name))(\(client)\(record)\(root.isSet ? ".asCase" : "")))")
            }
            code.line("    default:")
            code.line("        break")
            code.line("    }")
        }
        code.line("case .tick:")
        code.line("    try handler(.tick(\(client)number: event.tickNumber))")
        code.line("case .transferProgress:")
        code.line("    try handler(.transferProgress(\(client)route: event.route, transferId: event.transferId, bytes: event.bytes, total: event.total))")
        code.line("case .transferCancelled:")
        code.line("    try handler(.transferCancelled(\(client)route: event.route, transferId: event.transferId, code: event.code))")
        code.line("case .received:")
        code.line("    try handler(.received)")
        code.line("default:")
        code.line("    break")
        code.line("}")
        code.close()
        code.close()
    }

    // The topic members of a typed end that publishes: subscriptions on the server, the tick and the topic enum.
    static func tickMembers(_ code: inout Code, _ end: GesNetworkEndPlan, _ access: String, _ roots: (String) -> NetworkRoot) {
        if !end.client {
            for (verb, doc) in [("subscribe", "Subscribes a client to a topic."), ("unsubscribe", "Unsubscribes a client from a topic.")] {
                code.blank()
                code.line("/// \(doc)")
                code.line("/// - Parameters:")
                code.line("///   - client: The client.")
                code.line("///   - topic: The topic.")
                code.line("/// - Throws: `GesApiError.invalidArgument` when the client is not connected to the end.")
                code.line("\(access)func \(verb)(client: Int, topic: Topic) throws { try end.\(verb)(client: client, route: topic.rawValue) }")
            }
        }
        code.blank()
        code.line("/// Opens a tick, runs the body with it and closes it, also when the body throws: the tick's publications arrive together.")
        code.line("/// - Parameter body: The body; it publishes on the tick and includes latest topics.")
        code.line("/// - Returns: The status of closing the tick.")
        code.line("/// - Throws: `GesApiError.invalidOperation` when a tick is open already; an error of the body.")
        code.line("@discardableResult")
        code.open("\(access)func publishTick(_ body: (Tick) throws -> Void) throws -> GesNetworkSendStatus {")
        code.line("try end.beginTick()")
        code.open("do {")
        code.line("try body(Tick(self))")
        code.close("} catch {")
        code.indent()
        code.line("_ = try? end.endTick()")
        code.line("throw error")
        code.close()
        code.line("return try end.endTick()")
        code.close()
        code.blank()
        code.line("/// The topics the \(end.client ? "client" : "server") publishes.")
        code.open("\(access)enum Topic: Int, Sendable {")
        for route in end.topics {
            code.line("/// The topic `\(route.side) \(route.verb) :\(route.root) \(route.deliveryClass)`.")
            code.line("case \(name(GesSchemaPlanner.camel(route.root))) = \(route.index)")
        }
        code.close()
        code.blank()
        code.line("/// An open tick of `publishTick(_:)`: its publications arrive together.")
        code.open("\(access)struct Tick {")
        code.line("private let __end: \(end.name)")
        code.blank()
        code.line("fileprivate init(_ end: \(end.name)) { __end = end }")
        for route in end.topics {
            let root = roots(route.root)
            for (type, what) in root.isSet ? [(root.type, "record"), (root.type + ".Case", "message")] : [(root.type, "record")] {
                code.blank()
                code.line("/// Publishes a \(what) on the topic `:\(route.root)` as a member of the tick.")
                code.line("/// - Parameter value: The value.")
                code.line("/// - Returns: The status of the publication.")
                code.line("/// - Throws: `GesWireError` when a value does not fit its field.")
                code.line("@discardableResult")
                code.line("\(access)func publish(_ value: \(type)) throws(GesWireError) -> GesNetworkSendStatus { try __end.publish(value) }")
            }
        }
        code.blank()
        code.line("/// Makes a latest topic a member of the tick with its last published state.")
        code.line("/// - Parameter topic: The topic.")
        code.line("/// - Throws: `GesApiError.invalidOperation` when the topic has no published state; `GesApiError.invalidArgument` when it is no latest topic.")
        code.line("\(access)func include(_ topic: Topic) throws { try __end.end.include(route: topic.rawValue) }")
        code.close()
    }

    static func parameters(_ code: inout Code, _ client: Bool, _ value: String) {
        if !client {
            code.line("/// - Parameter value: \(value)")
            return
        }
        code.line("/// - Parameters:")
        code.line("///   - value: \(value)")
        code.line("///   - client: The client.")
    }

    // The events of a typed end, one case per event.
    static func endEvent(_ code: inout Code, _ network: GesLayoutNetwork, _ end: GesNetworkEndPlan, _ access: String, _ roots: (String) -> NetworkRoot) {
        let isClient = end.client
        let client = isClient ? "" : "client: Int, "

        func event(_ summary: String, _ declaration: String) {
            code.line("/// \(summary)")
            code.line("case \(declaration)")
        }

        code.blank()
        code.line("/// An event of the typed \(isClient ? "client" : "server") end `\(end.name)`.\(isClient ? "" : " Every event of a client carries the client.")")
        code.open("\(access)enum \(end.name)Event {")
        if isClient {
            event("The session is established, with the reached security.", "connected(security: GesNetworkSecurity)")
            event("The connection closed, with its code, its detail and whether the server closed it.", "disconnected(code: String, detail: String, byPeer: Bool)")
        } else {
            event(
                "A client asks to connect with its token, valid until the closure returns; refuse it with `Server.refuse(client:detail:)` before the closure returns, or it is accepted.",
                "connecting(client: Int, token: UnsafeRawBufferPointer)"
            )
            event("A client is connected, with the reached security.", "clientConnected(client: Int, security: GesNetworkSecurity)")
            event(
                "A client's connection closed, with its code, its detail and whether the client closed it; the client leaves the end.",
                "clientDisconnected(client: Int, code: String, detail: String, byPeer: Bool)"
            )
        }
        for (route, name) in end.incoming {
            let root = roots(route.root)
            event(
                "A \(root.isSet ? "message" : "record") arrived on the route `\(route.side) \(route.verb) :\(route.root) \(route.deliveryClass)`.",
                "\(self.name(GesSchemaPlanner.camel(name)))(\(client)\(root.isSet ? root.type + ".Case" : root.type))"
            )
        }
        event("A tick is complete; the events of its changed members precede it.", "tick(\(client)number: Int)")
        event(
            "A transfer on a bulk route advanced, with the route index, the transfer, the bytes received so far and the total bytes.",
            "transferProgress(\(client)route: Int, transferId: Int, bytes: Int64, total: Int64)"
        )
        event("A transfer was cancelled, with the route index, the transfer and the cancel code; the session continues.", "transferCancelled(\(client)route: Int, transferId: Int, code: String)")
        event("The last event of a poll that reported at least one message or tick.", "received")
        code.close()
    }

    // A named tag set, declared once beside the records that use it.
    static func tagSetDeclaration(_ code: inout Code, _ name: String, _ tags: [String], _ access: String) {
        code.blank()
        code.line("/// The tag set `:\(name)`, in declared order.")
        code.open("\(access)enum \(name): \(underlying(tags.count)), Sendable {")
        for tag in tags {
            code.line("/// The tag `#\(tag)`.")
            code.line("case \(self.name(tag))")
        }
        code.close()
    }

    // One bit per member in declared order, so the raw value is the wire mask. A member may not take the name of the mask.
    static func flagsDeclaration(_ code: inout Code, _ name: String, _ members: [String], _ access: String) throws(GesGeneratorError) {
        try GesSchemaPlanner.unique(name, [("rawValue", "the generated member rawValue")] + members.map { ($0, "the member #" + $0) })
        code.blank()
        code.line("/// The members of the field, one bit each in declared order.")
        code.open("\(access)struct \(name): OptionSet, Hashable, Sendable, Codable {")
        code.line("/// The mask, one bit per member in declared order.")
        code.line("\(access)let rawValue: UInt64")
        code.blank()
        code.line("/// Creates the members of a mask.")
        code.line("\(access)init(rawValue: UInt64) { self.rawValue = rawValue }")
        for (index, member) in members.enumerated() {
            code.blank()
            code.line("/// The member `#\(member)`.")
            code.line("\(access)static let \(self.name(member)) = \(name)(rawValue: 1 << \(index))")
        }
        code.close()
    }

    static func full(_ width: Int) -> UInt64 { width >= 64 ? .max : (1 << UInt64(width)) - 1 }

    static func long(_ value: Int64) -> String { value == .min ? "Int64.min" : String(value) }

    static func double(_ value: Int64) -> String { "\(value).0" }

    static func bits(_ value: Double) -> String { "Double(bitPattern: 0x\(GesSchemaLayoutJson.hex(value.bitPattern)))" }
