            GesBytecodeOpCode.EmitMessageValue => [MessageRegister],
            GesBytecodeOpCode.EmitMessageValueWithTags => [MessageRegister, TagRegisterList],
            GesBytecodeOpCode.PublishMessage => [OutboundMessage, ArgumentRegisterList],
